            % 0时

            if ki==1
                g0 = P.currentGrid;
                currentPlan = g0;
                currentChBase = P.currentChargeBase;
                currentDisBase = P.currentDischargeBase;
                plan0(kd,:) = ...
                    g0';

            % 6/12/18时调整

            else
                oldPlan = currentPlan(startSlot:end);
                currentPlan(startSlot:end) = ...
                    P.currentGrid;
                currentChBase(startSlot:end) = ...
                    P.currentChargeBase;
