% AS-Ridge负载

function [predToday,predNext] = buildCausalLoadASRidge( ...
    loadAll, ...
    dateAll, ...
    tau, ...
    lambda, ...
    maxIter, ...
    tol, ...
    windowDays)
[nDay,nTime] = ...
    size(loadAll);
predToday = nan(nDay,nTime);
predNext = nan(nDay,nTime);
slot = (0:nTime-1)';
sinDay = sin(2*pi*slot/nTime);
cosDay = cos(2*pi*slot/nTime);
for d = 16:nDay
    firstDay = max(15, d-windowDays);
    trainDays = firstDay:(d-1);
    X = zeros(length(trainDays)*nTime, 7);
    y = zeros(length(trainDays)*nTime, 1);
    r0 = 1;
    for j = trainDays
        rr = r0:(r0+nTime-1);
        wd = weekday(dateAll(j));
        X(rr,:) = ...
            [ ...
            loadAll(j-1,:)', ...
            loadAll(j-7,:)', ...
            loadAll(j-14,:)', ...
            sinDay, ...
            cosDay, ...
            repmat( ...
            sin(2*pi*(wd-1)/7), ...
            nTime,1), ...
            repmat( ...
            cos(2*pi*(wd-1)/7), ...
            nTime,1) ...
            ];
        y(rr) = ...
            loadAll(j,:)';
        r0 = r0+nTime;
    end
    wdToday = weekday(dateAll(d));
    Xtoday = ...
        [ ...
        loadAll(d-1,:)', ...
        loadAll(d-7,:)', ...
        loadAll(d-14,:)', ...
        sinDay, ...
        cosDay, ...
        repmat( ...
        sin(2*pi*(wdToday-1)/7), ...
        nTime,1), ...
        repmat( ...
        cos(2*pi*(wdToday-1)/7), ...
        nTime,1) ...
        ];
    yToday = fitASRidgeLocal(X, y, Xtoday, tau, lambda, maxIter, tol);
    wdNext = weekday(dateAll(d)+days(1));
    Xnext = ...
        [ ...
        yToday, ...
        loadAll(d+1-7,:)', ...
        loadAll(d+1-14,:)', ...
        sinDay, ...
        cosDay, ...
        repmat( ...
        sin(2*pi*(wdNext-1)/7), ...
        nTime,1), ...
        repmat( ...
        cos(2*pi*(wdNext-1)/7), ...
        nTime,1) ...
        ];
    yNext = fitASRidgeLocal(X, y, Xnext, tau, lambda, maxIter, tol);
    predToday(d,:) = ...
        max(yToday,0)';
    predNext(d,:) = ...
        max(yNext,0)';
end
end

% AS-Ridge

function yPred = fitASRidgeLocal( ...
    Xtrain, ...
    Ytrain, ...
    Xtest, ...
    tau, ...
    lambda, ...
    maxIter, ...
    tol)
muX = mean(Xtrain,1);
sdX = std(Xtrain,0,1);
sdX( ...
    sdX<1e-10 ...
    |~isfinite(sdX)) = ...
    1;
Xtr = (Xtrain-muX)./sdX;
Xte = (Xtest-muX)./sdX;
muY = mean(Ytrain);
sdY = std(Ytrain);
if sdY<1e-10 ...
        || ~isfinite(sdY)
    sdY = 1;
end
y = (Ytrain-muY)/sdY;
X1 = [ ones(size(Xtr,1),1), Xtr ];
Xt = [ ones(size(Xte,1),1), Xte ];
R = eye(size(X1,2));
R(1,1) = ...
    0;
beta = ( X1'*X1 +lambda*R) \(X1'*y);
for iter = 1:maxIter
    e = y -X1*beta;
    w = (1-tau) *ones(size(e));
    w(e>=0) = ...
        tau;
    w = max(w,1e-6);
    Xw = X1.*sqrt(w);
    yw = y.*sqrt(w);
    betaNew = ( Xw'*Xw +lambda*R) \(Xw'*yw);
    change = norm(betaNew-beta) /max(norm(beta), 1e-8);
    beta = betaNew;
    if change<tol
        break;
    end
end
yPred = (Xt*beta) *sdY +muY;
yPred = yPred(:);
end

% 附件3读取

function F = readForecastSingleSheet( ...
    filename, ...
    sheetName)
C = readcell(filename, 'Sheet',sheetName);
[nRow,nCol] = ...
    size(C);
headerRow = NaN;
for r = 1:min(nRow,30)
    for c = 1:nCol
        txt = replace(strtrim(string(C{r,c})), " ", "");
        if txt=="预报1小时" ...
                || txt=="预测1小时"
            headerRow = r;
            break;
        end
    end
    if ~isnan(headerRow)
        break;
    end
end
if isnan(headerRow)
    error( ...
        '附件3找不到表头。');
end
dateCol = NaN;
issueCol = NaN;
for c = 1:nCol
    txt = replace(strtrim(string(C{headerRow,c})), " ", "");
    if contains(txt,"日期")
        dateCol = c;
    end
    if contains(txt,"预报时刻") ...
            || contains(txt,"预测时刻")
        issueCol = c;
    end
end
forecastCols = nan(1,24);
for h = 1:24
    for c = 1:nCol
        txt = replace(strtrim(string(C{headerRow,c})), " ", "");
        if txt==sprintf( ...
                '预报%d小时',h) ...
                || txt==sprintf( ...
                '预测%d小时',h)
            forecastCols(h) = ...
                c;
            break;
        end
    end
    if isnan(forecastCols(h))
        error( ...
            '缺少预报%d小时列。', ...
            h);
    end
end
maxN = nRow-headerRow;
dates = NaT(maxN,1);
issueHour = nan(maxN,1);
forecast = nan(maxN,24);
count = 0;
currentDate = NaT;
for r = headerRow+1:nRow
    newDate = parseOneDate(C{r,dateCol});
    if ~isnat(newDate)
        currentDate = dateshift(newDate, 'start','day');
    end
    if isnat(currentDate)
        continue;
    end
    hIssue = parseIssueHour(C{r,issueCol});
    if isnan(hIssue) ...
            || ~ismember( ...
            hIssue, ...
            [0,6,12,18])
        continue;
    end
    vals = nan(1,24);
    for h = 1:24
        vals(h) = ...
            valueToDouble( ...
            C{r,forecastCols(h)});
    end
    if all(isnan(vals))
        continue;
    end
    count = count+1;
    dates(count) = ...
        currentDate;
    issueHour(count) = ...
        hIssue;
    forecast(count,:) = ...
        vals;
end
dates = dates(1:count);
issueHour = issueHour(1:count);
forecast = forecast(1:count,:);
T = table(dates, issueHour, (1:count)', 'VariableNames',{ 'Date','Hour','ID'});
T = sortrows(T, {'Date','Hour'});
id = T.ID;
F.dates = ...
    dates(id);
F.issueHour = ...
    issueHour(id);
F.forecast = ...
    forecast(id,:);
F.issueTime = ...
    F.dates ...
    +hours(F.issueHour);
end

% 日期解析

function d = parseOneDate(x)
d = NaT;
if iscell(x)
    if isempty(x)
        return;
    end
    x = x{1};
end
if isdatetime(x)
    if ~isnat(x)
        d = x(1);
    end
    return;
end
if isnumeric(x)
    if isempty(x) ...
            || isnan(x)
        return;
    end
    try
        d = datetime(x, 'ConvertFrom','excel');
        return;
    catch
    end
end
s = strtrim(string(x));
if ismissing(s) ...
        || strlength(s)==0
    return;
end
try
    d = datetime(s);
catch
    d = NaT;
end
end

% 发布时间解析

function h = parseIssueHour(x)
h = NaN;
if iscell(x)
    if isempty(x)
        return;
    end
    x = x{1};
end
if isduration(x)
    h = mod(round(hours(x)), 24);
    return;
end
if isdatetime(x)
    if ~isnat(x)
        h = hour(x);
    end
    return;
end
if isnumeric(x)
    if isempty(x) ...
            || isnan(x)
        return;
    end
    if x>=0 ...
            && x<1
        h = mod(round(24*x), 24);
        return;
    end
    if x>=0 ...
            && x<=24
        h = round(x);
        if h==24
            h = 0;
        end
        return;
    end
end
s = strtrim(string(x));
token = regexp(char(s), '(\d{1,2})\s*:', 'tokens','once');
if ~isempty(token)
    h = mod(str2double(token{1}), 24);
end
end

% 单元格转double

function y = valueToDouble(x)
y = NaN;
if iscell(x)
    if isempty(x)
        return;
    end
    x = x{1};
end
if isnumeric(x)
    if ~isempty(x)
        y = double(x(1));
    end
    return;
end
if islogical(x)
    y = double(x);
    return;
end
s = strtrim(string(x));
if ismissing(s) ...
        || strlength(s)==0
    return;
end
y = str2double(s);
end

