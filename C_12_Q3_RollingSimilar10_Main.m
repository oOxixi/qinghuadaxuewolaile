        A = ...
            replayActualBlockWithBase( ...
            loadAll(d,blockSlots)', ...
            pvAll(d,blockSlots)', ...
            currentPlan(blockSlots), ...
            currentChBase(blockSlots), ...
            currentDisBase(blockSlots), ...
