% Similar10 因果仿射滚动24h LP

function P = solveRolling24hCausalAffineLP( ...
    forecastNet, ...
    residualScenarios, ...
    prob, ...
    price24, ...
    qCurrent, ...
    g0Remain, ...
    Estart, ...
    forceFinalToday, ...
    Efinal, ...
    dt, ...
    eta, ...
    Emin, ...
    Emax, ...
    Wmax, ...
    terminalValue, ...
    cyclePenalty, ...
    curtailPenalty, ...
    options)
forecastNet = forecastNet(:);
price24 = price24(:);
H = length(forecastNet);
if H~=144
    error( ...
        '滚动窗口必须为144点。');
end
[K,H2] = ...
    size(residualScenarios);
if H2~=H
    error( ...
        '残差情景尺寸错误。');
end
prob = prob(:);
prob = prob/sum(prob);

% 转换为每10min电量

Wbase = forecastNet *dt;
R = residualScenarios *dt;
Rp = max(R,0);
Rn = max(-R,0);

% 变量
% G        未来24h共同普通购电
% 如果6/12/18时：
% INC DEC  当前日至午夜部分相对0时计划的调整量
% C0 D0    零残差基础储能轨迹
% ACP ACN ADP ADN
%          因果仿射响应系数
% Ebase    基础SOC
% SpBase   基础富余
% 对每个相似情景：
% E
% Em
% Sp

idxG = 1:H;
base = H;
isInitial = isempty(g0Remain);
if isInitial
    idxInc = [];
    idxDec = [];
else
    idxInc = base+(1:qCurrent);
    base = base+qCurrent;
    idxDec = base+(1:qCurrent);
    base = base+qCurrent;
    g0Remain = g0Remain(:);
end
idxC0 = base+(1:H);
base = base+H;
idxD0 = base+(1:H);
base = base+H;
idxACP = base+(1:H);
base = base+H;
idxACN = base+(1:H);
base = base+H;
idxADP = base+(1:H);
base = base+H;
idxADN = base+(1:H);
base = base+H;
idxEbase = base+(1:H+1);
base = base+H+1;
idxSpBase = base+(1:H);
base = base+H;
idxE = reshape(base+(1:K*(H+1)), H+1,K)';
base = base+K*(H+1);
idxEm = reshape(base+(1:K*H), H,K)';
base = base+K*H;
idxSp = reshape(base+(1:K*H), H,K)';
nVar = base+K*H;

% 目标函数

f = zeros(nVar,1);

% 整个24h普通购电
% 当前日剩余部分会实际执行，
% 午夜后的部分仅用于避免短视。

f(idxG) = ...
    price24;

% 6/12/18调整费用
% G = g0 + inc - dec
% p*G + 0.5p*inc + 0.5p*dec
% 等价题目：
% 增购1.5倍
% 减购支付0.5倍违约费

if ~isInitial
