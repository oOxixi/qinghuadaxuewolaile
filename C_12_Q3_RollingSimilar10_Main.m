            currentPlan(blockSlots)';
        baseChargePlan(kd,blockSlots) = ...
            currentChBase(blockSlots)';
        baseDischargePlan(kd,blockSlots) = ...
            currentDisBase(blockSlots)';
        actualCharge(kd,blockSlots) = ...
            A.Wch';
        actualDischarge(kd,blockSlots) = ...
            A.Wdis';
        actualEmergency(kd,blockSlots) = ...
            A.Wem';
        actualSurplus(kd,blockSlots) = ...
            A.Wsur';
        Ecurrent = A.Eend;
    end
    SOCend(kd) = ...
        Ecurrent;

    % 当日结算

