                    'Date', ...
                    'IssueHour', ...
                    'PVBlendWeight', ...
                    'SimilarCount', ...
                    'SimilarMeanDistance', ...
                    'ChangedSlots', ...
                    'IncreaseVs0_kWh', ...
                    'DecreaseVs0_kWh', ...
                    'RollingObjective', ...
                    'MaxConstraintViolation'} ...
                    );
                adjustmentTable = [adjustmentTable;logRow];
