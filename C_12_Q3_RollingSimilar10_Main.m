% 实际因果回放
% 保留P2思想：
% 先采用零残差基础充放电轨迹，
% 然后根据当前实际偏差即时修正。
% 不使用未来实际数据。

function A = replayActualBlockWithBase( ...
    Pload, ...
    Ppv, ...
    Wgrid, ...
    WchPlan, ...
    WdisPlan, ...
    Estart, ...
    globalSlots, ...
    forceFinalToday, ...
    Efinal, ...
    dt, ...
    eta, ...
    Emin, ...
    Emax, ...
    Wmax)
Wload = Pload(:)*dt;
Wpv = Ppv(:)*dt;
Wgrid = Wgrid(:);
WchPlan = WchPlan(:);
WdisPlan = WdisPlan(:);
N = length(Wgrid);
Wch = zeros(N,1);
Wdis = zeros(N,1);
Wem = zeros(N,1);
Wsur = zeros(N,1);
E = zeros(N+1,1);
E(1) = ...
    Estart;
for j = 1:N
    ec = E(j);
    tGlobal = globalSlots(j);

    % 下一时刻SOC允许区间

    if forceFinalToday
        remainingSlots = 144-tGlobal;
        nextLow = max(Emin, Efinal -remainingSlots *eta *Wmax);
        nextHigh = min(Emax, Efinal +remainingSlots *Wmax/eta);
    else
        nextLow = Emin;
        nextHigh = Emax;
    end

    % 基础储能计划

    c = min(max(WchPlan(j),0), Wmax);
    d = min(max(WdisPlan(j),0), Wmax);
    en = ec +eta*c -d/eta;

    % 基础动作若造成SOC过低：
    % 先减少放电，再增加充电

    if en<nextLow
        reduceDis = min(d, (nextLow-en)*eta);
        d = d-reduceDis;
        en = ec +eta*c -d/eta;
        if en<nextLow-1e-10
            addCh = min(Wmax-c, (nextLow-en)/eta);
            c = c+addCh;
            en = ec +eta*c -d/eta;
        end
    end

    % 基础动作SOC过高：
    % 先减少充电，再增加放电

    if en>nextHigh
        reduceCh = min(c, (en-nextHigh)/eta);
        c = c-reduceCh;
        en = ec +eta*c -d/eta;
        if en>nextHigh+1e-10
            addDis = min(Wmax-d, (en-nextHigh)*eta);
            d = d+addDis;
            en = ec +eta*c -d/eta;
        end
    end

    % 当前真实供需偏差
    % 正：缺电
    % 负：富余

    residual = Wload(j) -Wpv(j) -Wgrid(j) -(d-c);

    % 缺电

    if residual>1e-12

% 先减少充电

        maxReduceChargeSOC = max((en-nextLow)/eta, 0);
        reduceCharge = min([ residual, c, maxReduceChargeSOC ]);
        c = c-reduceCharge;
        residual = residual-reduceCharge;
        en = en -eta*reduceCharge;

% 再增加放电

        if residual>1e-12
            maxExtraDisSOC = eta *max(en-nextLow, 0);
            extraDis = min([ residual, Wmax-d, maxExtraDisSOC ]);
            d = d+extraDis;
            residual = residual-extraDis;
            en = en -extraDis/eta;
        end
        Wem(j) = ...
            max( ...
            residual, ...
            0);

    % 富余

    elseif residual<-1e-12
        surplus = -residual;

% 先减少放电

        maxReduceDisSOC = eta *max(nextHigh-en, 0);
        reduceDis = min([ surplus, d, maxReduceDisSOC ]);
        d = d-reduceDis;
        surplus = surplus-reduceDis;
        en = en +reduceDis/eta;

% 再增加充电

        if surplus>1e-12
            maxExtraChargeSOC = max(nextHigh-en, 0) /eta;
            extraCharge = min([ surplus, Wmax-c, maxExtraChargeSOC ]);
            c = c+extraCharge;
            surplus = surplus-extraCharge;
            en = en +eta*extraCharge;
        end
        Wsur(j) = ...
            max( ...
            surplus, ...
            0);
    end
    Enew = ec +eta*c -d/eta;
    if Enew<nextLow-1e-6 ...
            || Enew>nextHigh+1e-6
        error( ...
            ['实际回放SOC越界：', ...
             'slot=%d, E=%.8f'], ...
            tGlobal, ...
            Enew);
    end
    Wch(j) = ...
        c;
    Wdis(j) = ...
        d;
    E(j+1) = ...
        Enew;
end
A.Wch = ...
    Wch;
A.Wdis = ...
    Wdis;
A.Wem = ...
    Wem;
A.Wsur = ...
    Wsur;
A.E = ...
    E;
A.Eend = ...
    E(end);
end

