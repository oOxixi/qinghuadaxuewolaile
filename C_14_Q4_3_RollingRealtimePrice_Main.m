% 附件3读取

function F = readForecastSingleSheet( ...
    filename, ...
    sheetName)
C = readcell(filename, 'Sheet',sheetName);
[nRow,nCol] = ...
    size(C);
headerRow = NaN;
for r = 1:min(nRow,30)
    for c = 1:nCol
        txt = replace(strtrim(string(C{r,c})), " ","");
        if txt=="预报1小时" ...
                ||txt=="预测1小时"
            headerRow = r;
            break;
        end
    end
    if ~isnan(headerRow)
        break;
    end
end
if isnan(headerRow)
    error( ...
        '附件3找不到表头。');
end
dateCol = NaN;
issueCol = NaN;
for c = 1:nCol
    txt = replace(strtrim(string(C{headerRow,c})), " ","");
    if contains(txt,"日期")
        dateCol = c;
    end
    if contains(txt,"预报时刻") ...
            ||contains(txt,"预测时刻")
        issueCol = c;
    end
end
forecastCols = nan(1,24);
for h = 1:24
    for c = 1:nCol
        txt = replace(strtrim(string(C{headerRow,c})), " ","");
        if txt==sprintf('预报%d小时',h) ...
                ||txt==sprintf('预测%d小时',h)
            forecastCols(h) = ...
                c;
            break;
        end
    end
end
maxN = nRow-headerRow;
dates = NaT(maxN,1);
issueHour = nan(maxN,1);
forecast = nan(maxN,24);
count = 0;
currentDate = NaT;
for r = headerRow+1:nRow
    newDate = parseOneDate(C{r,dateCol});
    if ~isnat(newDate)
        currentDate = dateshift(newDate, 'start','day');
    end
    if isnat(currentDate)
        continue;
    end
    hIssue = parseIssueHour(C{r,issueCol});
    if isnan(hIssue) ...
            ||~ismember( ...
            hIssue,[0,6,12,18])
        continue;
    end
    vals = nan(1,24);
    for h = 1:24
        vals(h) = ...
            valueToDouble( ...
            C{r,forecastCols(h)});
    end
    if all(isnan(vals))
        continue;
    end
    count = count+1;
    dates(count) = ...
        currentDate;
    issueHour(count) = ...
        hIssue;
    forecast(count,:) = ...
        vals;
end
dates = dates(1:count);
issueHour = issueHour(1:count);
forecast = forecast(1:count,:);
T = table(dates, issueHour, (1:count)', 'VariableNames', {'Date','Hour','ID'});
T = sortrows(T, {'Date','Hour'});
id = T.ID;
F.dates = dates(id);
F.issueHour = issueHour(id);
F.forecast = forecast(id,:);
F.issueTime = F.dates +hours(F.issueHour);
end

% 日期解析

function d = parseOneDate(x)
d = NaT;
if iscell(x)
    if isempty(x)
        return;
    end
    x = x{1};
end
if isdatetime(x)
    if ~isnat(x)
        d = x(1);
    end
    return;
end
if isnumeric(x)
    if isempty(x) ...
            ||isnan(x)
        return;
    end
    try
        d = datetime(x, 'ConvertFrom','excel');
        return;
    catch
    end
end
s = strtrim(string(x));
if ismissing(s) ...
        ||strlength(s)==0
    return;
end
try
    d = datetime(s);
catch
    d = NaT;
end
end

% 发布时间解析

function h = parseIssueHour(x)
h = NaN;
if iscell(x)
    if isempty(x)
        return;
    end
    x = x{1};
end
if isduration(x)
    h = mod(round(hours(x)), 24);
    return;
end
if isdatetime(x)
    if ~isnat(x)
        h = hour(x);
    end
    return;
end
if isnumeric(x)
    if isempty(x) ...
            ||isnan(x)
        return;
    end
    if x>=0 ...
            &&x<1
        h = mod(round(24*x), 24);
        return;
    end
    if x>=0 ...
            &&x<=24
        h = round(x);
        if h==24
            h = 0;
        end
        return;
    end
end
s = strtrim(string(x));
token = regexp(char(s), '(\d{1,2})\s*:', 'tokens','once');
if ~isempty(token)
    h = mod(str2double(token{1}), 24);
end
end

function y = valueToDouble(x)
y = NaN;
if iscell(x)
    if isempty(x)
        return;
    end
    x = x{1};
end
if isnumeric(x)
    if ~isempty(x)
        y = double(x(1));
    end
    return;
end
if islogical(x)
    y = double(x);
    return;
end
s = strtrim(string(x));
if ismissing(s) ...
        ||strlength(s)==0
    return;
end
y = str2double(s);
end

