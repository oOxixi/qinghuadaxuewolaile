% Similar10选择

function S = getSimilarResidualScenarios( ...
    Rlib, ...
    issueHour, ...
    currentTime, ...
    currentLoad24, ...
    currentPV24, ...
    historyWindow, ...
    minHistory, ...
    similarCount)
valid = Rlib.complete &Rlib.issueHour==issueHour &( Rlib.issueTime+hours(24) <=currentTime);
rows = find(valid);
if isempty(rows)
    S.netResidual = zeros(1,144);
    S.prob = 1;
    S.nHistory = 0;
    S.nSelected = 1;
    S.meanDistance = NaN;
    return;
end
[~,ord] = ...
    sort(Rlib.issueTime(rows));
rows = rows(ord);
firstKeep = max(1, length(rows)-historyWindow+1);
rows = rows(firstKeep:end);
nHistory = length(rows);
if nHistory<minHistory
    S.netResidual = zeros(1,144);
    S.prob = 1;
    S.nHistory = nHistory;
    S.nSelected = 1;
    S.meanDistance = NaN;
    return;
end
currentLoad24 = currentLoad24(:)';
currentPV24 = currentPV24(:)';
loadScale = max(mean(abs(currentLoad24)), 1);
pvScale = max(mean(abs(currentPV24)), 1);
loadDistance = sqrt(mean(( ( Rlib.baseLoad(rows,:) -currentLoad24) /loadScale).^2, 2));
pvDistance = sqrt(mean(( ( Rlib.basePV(rows,:) -currentPV24) /pvScale).^2, 2));
totalDistance = loadDistance +pvDistance;
[~,order] = ...
    sort( ...
    totalDistance, ...
    'ascend');
keepN = min(similarCount, length(order));
keep = order(1:keepN);
selectedRows = rows(keep);
S.netResidual = Rlib.eNet(selectedRows,:);
S.prob = ones(keepN,1) /keepN;
S.nHistory = nHistory;
S.nSelected = keepN;
S.meanDistance = mean(totalDistance(keep));
S.selectedDate = Rlib.date(selectedRows);
end

% Similar10因果仿射24h滚动LP

function P = solveRolling24hCausalAffineLP( ...
    forecastNet, ...
    residualScenarios, ...
    prob, ...
    price24, ...
    qCurrent, ...
    g0Remain, ...
    Estart, ...
    forceFinalToday, ...
    Efinal, ...
    eta, ...
    Emin, ...
    Emax, ...
    Wmax, ...
    terminalValue, ...
    cyclePenalty, ...
    curtailPenalty, ...
    options)
H = 144;
dt = 1/6;
forecastNet = forecastNet(:);
price24 = price24(:);
[K,H2] = ...
    size(residualScenarios);
if length(forecastNet)~=H ...
        ||H2~=H
    error( ...
        '预测与残差必须为144点。');
end
prob = prob(:);
prob = prob/sum(prob);
Wbase = forecastNet' *dt;
R = residualScenarios *dt;
Rp = max(R,0);
Rn = max(-R,0);

% 变量编号

idxG = 1:H;
base = H;
isInitial = isempty(g0Remain);
if isInitial
    idxInc = [];
    idxDec = [];
else
    idxInc = base+(1:qCurrent);
    base = base+qCurrent;
    idxDec = base+(1:qCurrent);
    base = base+qCurrent;
    g0Remain = g0Remain(:);
end
idxC0 = base+(1:H);
base = base+H;
idxD0 = base+(1:H);
base = base+H;
idxACP = base+(1:H);
base = base+H;
idxACN = base+(1:H);
base = base+H;
idxADP = base+(1:H);
base = base+H;
idxADN = base+(1:H);
base = base+H;
idxEbase = base+(1:H+1);
base = base+H+1;
idxSpBase = base+(1:H);
base = base+H;
idxE = reshape(base+(1:K*(H+1)), H+1,K)';
base = base+K*(H+1);
idxEm = reshape(base+(1:K*H), H,K)';
base = base+K*H;
idxSp = reshape(base+(1:K*H), H,K)';
nVar = base+K*H;

% 目标函数

f = zeros(nVar,1);

% 普通购电使用预测实时价格
f(idxG) = ...
    price24;

% 调整
if ~isInitial
    f(idxInc) = ...
        0.5 ...
        *price24(1:qCurrent);
    f(idxDec) = ...
        0.5 ...
        *price24(1:qCurrent);
end

% Scenario成本
for s = 1:K
    f(idxEm(s,:)) = ...
        prob(s) ...
        *5 ...
        *price24;
    f(idxSp(s,:)) = ...
        prob(s) ...
        *curtailPenalty;
    f(idxE(s,end)) = ...
        f(idxE(s,end)) ...
        -prob(s)*terminalValue;
end
f(idxSpBase) = ...
    curtailPenalty;

% 充放电吞吐tie-break
mRp = (prob'*Rp)';
mRn = (prob'*Rn)';
f(idxC0) = ...
    cyclePenalty;
f(idxD0) = ...
    cyclePenalty;
f(idxACP) = ...
    -cyclePenalty*mRp;
f(idxACN) = ...
    cyclePenalty*mRn;
f(idxADP) = ...
    cyclePenalty*mRp;
f(idxADN) = ...
    -cyclePenalty*mRn;

% 等式约束

nAdjustEq = double(~isInitial) *qCurrent;
nBaseEq = 2*H+1;
nScenarioEq = K*(2*H+1);
nEq = nAdjustEq +nBaseEq +nScenarioEq;
Aeq = spalloc(nEq, nVar, 20*nEq);
beq = zeros(nEq,1);
row = 0;

% 调整关系
if ~isInitial
    for t = 1:qCurrent
        row = row+1;
        Aeq(row,idxG(t)) = ...
            1;
        Aeq(row,idxInc(t)) = ...
            -1;
        Aeq(row,idxDec(t)) = ...
            1;
        beq(row) = ...
            g0Remain(t);
    end
end

% 基础路径供需
for t = 1:H
    row = row+1;
    Aeq(row,idxG(t)) = ...
        1;
    Aeq(row,idxD0(t)) = ...
        1;
    Aeq(row,idxC0(t)) = ...
        -1;
    Aeq(row,idxSpBase(t)) = ...
        -1;
    beq(row) = ...
        Wbase(t);
end

% 基础SOC
for t = 1:H
    row = row+1;
    Aeq(row,idxEbase(t)) = ...
        -1;
    Aeq(row,idxEbase(t+1)) = ...
        1;
    Aeq(row,idxC0(t)) = ...
        -eta;
    Aeq(row,idxD0(t)) = ...
        1/eta;
end
row = row+1;
Aeq(row,idxEbase(1)) = ...
    1;
beq(row) = ...
    Estart;

% Scenario
for s = 1:K
    for t = 1:H
        row = row+1;
        Aeq(row,idxG(t)) = ...
            1;
        Aeq(row,idxC0(t)) = ...
            -1;
        Aeq(row,idxD0(t)) = ...
            1;
        Aeq(row,idxACP(t)) = ...
            Rp(s,t);
        Aeq(row,idxACN(t)) = ...
            -Rn(s,t);
        Aeq(row,idxADP(t)) = ...
            Rp(s,t);
        Aeq(row,idxADN(t)) = ...
            -Rn(s,t);
        Aeq(row,idxEm(s,t)) = ...
            1;
        Aeq(row,idxSp(s,t)) = ...
            -1;
        beq(row) = ...
            Wbase(t) ...
            +R(s,t);
    end
    for t = 1:H
        row = row+1;
        Aeq(row,idxE(s,t)) = ...
            -1;
        Aeq(row,idxE(s,t+1)) = ...
            1;
        Aeq(row,idxC0(t)) = ...
            -eta;
        Aeq(row,idxD0(t)) = ...
            1/eta;
        Aeq(row,idxACP(t)) = ...
            eta*Rp(s,t);
        Aeq(row,idxACN(t)) = ...
            -eta*Rn(s,t);
        Aeq(row,idxADP(t)) = ...
            Rp(s,t)/eta;
        Aeq(row,idxADN(t)) = ...
            -Rn(s,t)/eta;
    end
    row = row+1;
    Aeq(row,idxE(s,1)) = ...
        1;
    beq(row) = ...
        Estart;
end

% 不等式：情景充放电范围

nIneq = 4*K*H;
A = spalloc(nIneq, nVar, 12*K*H);
b = zeros(nIneq,1);
row = 0;
for s = 1:K
    for t = 1:H

% C <= Wmax
        row = row+1;
        A(row,idxC0(t)) = ...
            1;
        A(row,idxACP(t)) = ...
            -Rp(s,t);
        A(row,idxACN(t)) = ...
            Rn(s,t);
        b(row) = ...
            Wmax;

% C >= 0
        row = row+1;
        A(row,idxC0(t)) = ...
            -1;
        A(row,idxACP(t)) = ...
            Rp(s,t);
        A(row,idxACN(t)) = ...
            -Rn(s,t);

% D <= Wmax
        row = row+1;
        A(row,idxD0(t)) = ...
            1;
        A(row,idxADP(t)) = ...
            Rp(s,t);
        A(row,idxADN(t)) = ...
            -Rn(s,t);
        b(row) = ...
            Wmax;

% D >= 0
        row = row+1;
        A(row,idxD0(t)) = ...
            -1;
        A(row,idxADP(t)) = ...
            -Rp(s,t);
        A(row,idxADN(t)) = ...
            Rn(s,t);
    end
end

% 上下界

lb = zeros(nVar,1);
ub = inf(nVar,1);
ub(idxC0) = ...
    Wmax;
ub(idxD0) = ...
    Wmax;
ub([
    idxACP
    idxACN
    idxADP
    idxADN
    ]) = ...
    1;
lb(idxEbase) = ...
    Emin;
