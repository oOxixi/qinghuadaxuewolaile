    thisDate = predDates(kd);
    for ki = 1:4
        hIssue = issueHours(ki);
        currentTime = thisDate +hours(hIssue);
        [ ...
            wDynamic(kd,ki), ...
            nWeightHistory(kd,ki) ...
            ] = ...
            getRollingPVBlendWeight( ...
            PVlib, ...
            hIssue, ...
            currentTime, ...
            PV_BLEND_WINDOW, ...
            PV_BLEND_MIN_HISTORY);
    end
end
