            filesNeed{i});
    end
end

% 储能与时间参数

dt = 1/6;
eta = 0.90;
Ecapacity = 12000;
Emin = 1200;
Emax = 10800;
Einitial = 6000;
Efinal = 6000;
Pmax = 5000;
Wmax = Pmax*dt;
issueHours = [0,6,12,18];

% Similar10参数

SIMILAR_WINDOW = 30;
SIMILAR_MIN_HISTORY = 7;
