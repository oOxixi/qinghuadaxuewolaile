% 光伏融合参数

PV_BLEND_WINDOW = 30;
PV_BLEND_MIN_HISTORY = 7;

% 电价预测参数

PRICE_KL = 1;
PRICE_KS = 2;
USE_PRICE_ROLLING_UPDATE = true;

% 优化参数

cyclePenalty = 1e-5;
curtailPenalty = 1e-5;
USE_TERMINAL_VALUE = true;
FORCE_FINAL_SOC_6000 = false;
WRITE_OFFICIAL_RESULT43 = true;

%% 数据读取与时间轴

dateAll = ( datetime(2025,1,1): days(1): datetime(2025,12,31))';
targetDays = 32:365;
predDatesDefault = dateAll(targetDays);
nDay = 334;
nTime = 144;

% 问题2负载预测

fprintf('读取问题2最终MAT...\n');
Q2 = load(Q2File);
if ~isfield(Q2,'predLoad')
    error( ...
        '问题2 MAT中找不到 predLoad。');
end
predLoad = Q2.predLoad;
if ~isequal(size(predLoad),[334,144])
    error( ...
        '问题2 predLoad必须为334×144。');
end
predLoad = max(predLoad,0);
if isfield(Q2,'predDates')
    predDates = Q2.predDates(:);
else
    predDates = predDatesDefault;
end
if length(predDates)~=334
    error( ...
        'predDates必须为334天。');
end
fprintf('AS-Ridge负载预测读取完成。\n');
fprintf('问题4-3不再重新训练AS-Ridge。\n\n');

% 真实负载与光伏

fprintf('读取附件2...\n');
loadAll = readmatrix(actualFile, 'Sheet','小区负载', 'Range','B2:EO366');
pvAll = readmatrix(actualFile, 'Sheet','光伏发电实际功率', 'Range','B2:EO366');
if ~isequal(size(loadAll),[365,144]) ...
        ||~isequal(size(pvAll),[365,144])
    error( ...
        '附件2必须为365×144。');
end
if any(~isfinite(loadAll),'all') ...
        ||any(~isfinite(pvAll),'all')
    error( ...
        '附件2存在非法值。');
end
fprintf('附件2读取完成。\n\n');

% 实际实时电价

fprintf('读取附件4实时电价...\n');
priceSheets = sheetnames(priceFile);
priceAll = readmatrix(priceFile, 'Sheet',priceSheets(1), 'Range','B2:EO366');
if ~isequal(size(priceAll),[365,144])
    error( ...
        '附件4必须为365×144。');
end
if any(~isfinite(priceAll),'all') ...
        ||any(priceAll<0,'all')
    error( ...
        '附件4存在非法电价。');
end
actualPriceRun = priceAll(targetDays,:);

%% 滚动实时电价预测

fprintf('生成严格因果滚动实时电价预测...\n');
[ ...
    priceForecastCache, ...
    priceForecastDiagTable, ...
    price0hMAE, ...
    priceBlockMAE ...
    ] = ...
    buildRollingPriceForecastCache( ...
    priceAll, ...
    dateAll, ...
    targetDays, ...
    issueHours, ...
    PRICE_KL, ...
    PRICE_KS, ...
    USE_PRICE_ROLLING_UPDATE);
fprintf('\n');
fprintf(' 实时电价预测诊断\n');
fprintf( ...
    '0时完整144点MAE：%.6f 元/kWh\n', ...
    price0hMAE);
for ki = 1:4
    fprintf( ...
        '%2d时后未来6h MAE：%.6f 元/kWh\n', ...
        issueHours(ki), ...
        priceBlockMAE(ki));
end

%% 光伏动态融合

fprintf('读取附件3...\n');
F = readForecastSingleSheet(forecastFile, 'Sheet1');
if ~all( ...
        ismember( ...
        issueHours, ...
        unique(F.issueHour)'))
    error( ...
        '附件3未完整包含0/6/12/18时预报。');
