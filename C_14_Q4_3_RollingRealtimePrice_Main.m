% 当前发布时间未来24h价格

function price24 = makeRollingPrice24( ...
    priceAll, ...
    dateAll, ...
    d, ...
    issueHour, ...
    kL, ...
    kS, ...
    useRollingUpdate)
[ ...
    todayBase, ...
    todayShape, ...
    ~ ...
    ] = ...
    makeBaseCalendarPriceForecast( ...
    priceAll, ...
    dateAll, ...
    dateAll(d), ...
    d-1, ...
    kL, ...
    kS);
todayForecast = todayBase;

% 当前日滚动修正

if useRollingUpdate ...
        &&issueHour>0
    obsN = issueHour*6;
    observedPrice = priceAll(d,1:obsN)';
    observedShape = todayShape(1:obsN)';
    denom = sum(observedShape.^2);
    if denom>1e-12
        updatedLevel = sum(observedShape .*observedPrice) /denom;
        if isfinite(updatedLevel) ...
                &&updatedLevel>=0
            todayForecast = updatedLevel .*todayShape;
        end
    end
end
todayForecast = max(todayForecast,0);

% 次日预测

nextDate = dateAll(d) +days(1);
[nextForecast,~,~] = ...
    makeBaseCalendarPriceForecast( ...
    priceAll, ...
    dateAll, ...
    nextDate, ...
    d-1, ...
    kL, ...
    kS);
startSlot = issueHour*6+1;
price24 = [ todayForecast(startSlot:end), nextForecast(1:startSlot-1) ]';
if length(price24)~=144
    error( ...
        '滚动价格长度错误。');
end
end

% 基础日价格预测

function [ ...
    forecastDay, ...
    shapeDay, ...
    levelDay ...
    ] = ...
    makeBaseCalendarPriceForecast( ...
    priceAll, ...
    dateAll, ...
    targetDate, ...
    lastCompleteDay, ...
    kL, ...
    kS)
histDays = (1:lastCompleteDay)';
targetWeekday = weekday(targetDate);
histWeekday = weekday(dateAll(histDays));
sameWeekDays = histDays(histWeekday==targetWeekday);
if length(sameWeekDays)<max(kL,kS)
    error( ...
        '电价同星期历史不足。');
end
meanDays = sameWeekDays(end-kL+1:end);
levelDay = mean(mean(priceAll(meanDays,:), 2));
