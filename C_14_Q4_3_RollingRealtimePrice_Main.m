        'Q4-3 Similar10 LP失败：%s', ...
        output.message);
end
eqViolation = max(abs(Aeq*x-beq));
ineqViolation = max([ A*x-b; 0 ]);
boundViolation = max([ lb-x; x-ub; 0 ]);
P.currentGrid = x(idxG(1:qCurrent));
P.currentChargeBase = x(idxC0(1:qCurrent));
P.currentDischargeBase = x(idxD0(1:qCurrent));
P.objective = fval;
P.maxConstraintViolation = max([ eqViolation; ineqViolation; boundViolation ]);
end

% 实际因果执行

function A = replayActualBlockWithBase( ...
    Pload, ...
    Ppv, ...
    Wgrid, ...
    WchPlan, ...
    WdisPlan, ...
    Estart, ...
    globalSlots, ...
    forceFinalToday, ...
    Efinal, ...
    eta, ...
    Emin, ...
    Emax, ...
    Wmax)
dt = 1/6;
Wload = Pload(:)*dt;
Wpv = Ppv(:)*dt;
Wgrid = Wgrid(:);
WchPlan = WchPlan(:);
WdisPlan = WdisPlan(:);
N = length(Wgrid);
Wch = zeros(N,1);
Wdis = zeros(N,1);
Wem = zeros(N,1);
Wsur = zeros(N,1);
E = zeros(N+1,1);
E(1) = ...
    Estart;
for j = 1:N
    ec = E(j);
    tGlobal = globalSlots(j);
    if forceFinalToday
        remainingSlots = 144-tGlobal;
        nextLow = max(Emin, Efinal -remainingSlots*eta*Wmax);
        nextHigh = min(Emax, Efinal +remainingSlots*Wmax/eta);
    else
        nextLow = Emin;
        nextHigh = Emax;
    end
    c = min(max(WchPlan(j),0), Wmax);
    d = min(max(WdisPlan(j),0), Wmax);
    en = ec +eta*c -d/eta;

% SOC太低
    if en<nextLow
        rd = min(d, (nextLow-en)*eta);
        d = d-rd;
        en = ec +eta*c -d/eta;
    end

% SOC太高
    if en>nextHigh
        rc = min(c, (en-nextHigh)/eta);
        c = c-rc;
        en = ec +eta*c -d/eta;
    end
    residual = Wload(j) -Wpv(j) -Wgrid(j) -(d-c);

% 缺电
    if residual>1e-12
        reduceCharge = min([ residual, c, max((en-nextLow)/eta, 0) ]);
        c = c-reduceCharge;
        residual = residual-reduceCharge;
        en = en -eta*reduceCharge;
        if residual>1e-12
            extraDis = min([ residual, Wmax-d, eta*max(en-nextLow,0) ]);
            d = d+extraDis;
            residual = residual-extraDis;
            en = en -extraDis/eta;
        end
        Wem(j) = ...
            max(residual,0);

% 富余
    elseif residual<-1e-12
        surplus = -residual;
        reduceDis = min([ surplus, d, eta*max(nextHigh-en,0) ]);
        d = d-reduceDis;
        surplus = surplus-reduceDis;
        en = en +reduceDis/eta;
        if surplus>1e-12
            extraCh = min([ surplus, Wmax-c, max(nextHigh-en,0)/eta ]);
            c = c+extraCh;
            surplus = surplus-extraCh;
            en = en +eta*extraCh;
        end
        Wsur(j) = ...
            max(surplus,0);
    end
    Enew = ec +eta*c -d/eta;
    if Enew<nextLow-1e-6 ...
            ||Enew>nextHigh+1e-6
        error( ...
            '实际回放SOC越界：slot=%d SOC=%.9f', ...
            tGlobal,Enew);
    end
    Wch(j) = ...
        c;
    Wdis(j) = ...
        d;
    E(j+1) = ...
        Enew;
end
A.Wch = Wch;
A.Wdis = Wdis;
A.Wem = Wem;
A.Wsur = Wsur;
A.E = E;
A.Eend = E(end);
end

% PV历史标定库

function L = buildPVBlendCalibrationLibrary( ...
    F, ...
    pvAll, ...
    dateAll)
nRec = length(F.dates);
formal = nan(nRec,144);
history = nan(nRec,144);
actual = nan(nRec,144);
complete = false(nRec,1);
for i = 1:nRec
    d = find(dateAll==F.dates(i), 1);
    if isempty(d) ...
            ||d<=3
        continue;
    end
    hIssue = F.issueHour(i);
    actual24 = extractActual24(pvAll,d,hIssue);
    if isempty(actual24)
        continue;
    end
    formal24 = makeFormalPV24(F,pvAll,dateAll,d,hIssue);
    history24 = makeHistoryPV24(pvAll,d,hIssue);
    formal(i,:) = ...
        formal24';
    history(i,:) = ...
        history24';
    actual(i,:) = ...
        actual24';
    complete(i) = ...
        all(isfinite(formal(i,:))) ...
        &&all(isfinite(history(i,:))) ...
        &&all(isfinite(actual(i,:)));
end
L.date = F.dates;
L.issueHour = F.issueHour;
L.issueTime = F.issueTime;
L.formal = formal;
L.history = history;
L.actual = actual;
L.complete = complete;
end

% PV融合权重

function [w,nHistory] = getRollingPVBlendWeight( ...
    L, ...
    issueHour, ...
    currentTime, ...
    windowN, ...
    minHistory)
valid = L.complete &L.issueHour==issueHour &( L.issueTime+hours(24) <=currentTime);
rows = find(valid);
if isempty(rows)
    w = 1;
    nHistory = 0;
    return;
end
[~,ord] = ...
    sort(L.issueTime(rows));
rows = rows(ord);
rows = rows(max(1, length(rows)-windowN+1):end);
nHistory = length(rows);
if nHistory<minHistory
    w = 1;
    return;
end
formal = L.formal(rows,:);
history = L.history(rows,:);
actual = L.actual(rows,:);
formal = formal(:);
history = history(:);
actual = actual(:);
good = isfinite(formal) &isfinite(history) &isfinite(actual);
formal = formal(good);
history = history(good);
actual = actual(good);
den = sum((formal-history).^2);
if isempty(actual) ...
        ||den<1e-12
    w = 1;
    return;
end
w = sum((actual-history) .*(formal-history)) /den;
w = min(max(w,0), 1);
end

% 正式PV24h

function formal24 = makeFormalPV24( ...
    F, ...
    pvAll, ...
    dateAll, ...
    d, ...
    issueHour)
date0 = dateAll(d);
id = find(F.dates==date0 &F.issueHour==issueHour, 1);
if isempty(id)
    error( ...
        '找不到%s %02d时PV预报。', ...
        string(date0), ...
        issueHour);
end
anchor = observedPVAtIssue(pvAll,d,issueHour);
xSlot = 0:6:144;
querySlot = 1:144;
formal24 = interp1(xSlot, [anchor,F.forecast(id,:)], querySlot, 'linear')';
formal24 = max(formal24,0);
end

% PV动态融合

function pv24 = makeOfficialPV24Blend( ...
    F, ...
    pvAll, ...
    dateAll, ...
    d, ...
    issueHour, ...
    w)
formal24 = makeFormalPV24(F,pvAll,dateAll,d,issueHour);
history24 = makeHistoryPV24(pvAll,d,issueHour);
pv24 = w*formal24 +(1-w)*history24;
pv24 = max(pv24,0);
end

% 前3日PV

function history24 = makeHistoryPV24( ...
    pvAll, ...
    d, ...
    issueHour)
