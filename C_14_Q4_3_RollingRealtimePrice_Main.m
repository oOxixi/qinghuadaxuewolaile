if forceFinalToday
    midnightState = qCurrent+1;
    lb(idxEbase(midnightState)) = ...
        Efinal;
    ub(idxEbase(midnightState)) = ...
        Efinal;
    for s = 1:K
        lb(idxE(s,midnightState)) = ...
            Efinal;
        ub(idxE(s,midnightState)) = ...
            Efinal;
    end
end

% 求解

[x,fval,exitflag,output] = ...
    linprog( ...
