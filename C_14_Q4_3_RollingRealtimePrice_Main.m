    if abs(oneMean)<1e-12
        error( ...
            '历史日均价格接近0。');
    end
    shapeMatrix(k,:) = ...
        onePrice ...
        /oneMean;
end
shapeDay = mean(shapeMatrix, 1);
forecastDay = max(levelDay .*shapeDay, 0);
end

