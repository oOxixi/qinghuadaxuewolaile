% 0/6/12/18时滚动求解

fprintf(' 开始Q4-3滚动优化\n');
timerAll = tic;
for kd = 1:nDay
    thisDate = predDates(kd);
    dFull = find(dateAll==thisDate, 1);
    if isempty(dFull)
        error( ...
            '日期映射失败：%s', ...
            string(thisDate));
    end
    actualPriceDay = priceAll(dFull,:)';
    isLastDay = kd==nDay;
    forceFinalToday = isLastDay &&FORCE_FINAL_SOC_6000;
    SOCstart(kd) = ...
        Ecurrent;
    currentPlan = zeros(144,1);
    currentChBase = zeros(144,1);
    currentDisBase = zeros(144,1);
    g0 = zeros(144,1);
    if mod(kd-1,20)==0 ...
            ||isLastDay
        fprintf( ...
            '[%03d/%03d] %s | SOC %.2f\n', ...
            kd, ...
            nDay, ...
            string(thisDate), ...
            Ecurrent);
    end

    % 每日0 / 6 / 12 / 18

    for ki = 1:4
        hIssue = issueHours(ki);
        startSlot = hIssue*6+1;
        endSlot = min(startSlot+35, 144);
        blockSlots = startSlot:endSlot;
        qCurrent = 144-startSlot+1;

% 14.1 AS-Ridge未来24h负载

        baseLoad24 = makeQ2LoadForecast24(predLoad, kd, hIssue, true);

% 14.2 动态融合未来24h PV

        wNow = wDynamic(kd,ki);
        basePV24 = makeOfficialPV24Blend(F, pvAll, dateAll, dFull, hIssue, wNow);

% 14.3 Similar10

        currentTime = thisDate +hours(hIssue);
        S = ...
            getSimilarResidualScenarios( ...
            Rlib, ...
            hIssue, ...
            currentTime, ...
            baseLoad24, ...
            basePV24, ...
            SIMILAR_WINDOW, ...
            SIMILAR_MIN_HISTORY, ...
            SIMILAR_COUNT);
        similarN(kd,ki) = ...
            S.nSelected;
        similarMeanDistance(kd,ki) = ...
            S.meanDistance;

% 14.4 基础净负荷

        forecastNet24 = baseLoad24(:) -basePV24(:);

% 14.5 当前发布时间预测实时电价

        price24 = priceForecastCache{kd,ki};
        price24 = price24(:);
        if length(price24)~=144
            error( ...
                '滚动实时电价长度不是144。');
        end

% 14.6 相对0时原计划

        if ki==1
            g0Remain = [];
        else
            g0Remain = g0(startSlot:end);
        end

% 14.7 终端SOC价值

        if USE_TERMINAL_VALUE ...
                &&~isLastDay
            terminalValueNow = eta *mean(price24);
        else
            terminalValueNow = 0;
        end

% 14.8 Similar10 + Causal Affine滚动LP

        P = ...
            solveRolling24hCausalAffineLP( ...
            forecastNet24, ...
            S.netResidual, ...
            S.prob, ...
            price24, ...
            qCurrent, ...
            g0Remain, ...
            Ecurrent, ...
            forceFinalToday, ...
            Efinal, ...
            eta, ...
            Emin, ...
            Emax, ...
            Wmax, ...
            terminalValueNow, ...
            cyclePenalty, ...
            curtailPenalty, ...
            lpOptions);
        maxLPViolation = max(maxLPViolation, P.maxConstraintViolation);

        % 0时形成基准计划

        if ki==1
            g0 = P.currentGrid;
            currentPlan = g0;
            currentChBase = P.currentChargeBase;
            currentDisBase = P.currentDischargeBase;
            plan0(kd,:) = ...
                g0';

        % 6/12/18调整

        else
            oldPlan = currentPlan(startSlot:end);
            currentPlan(startSlot:end) = ...
                P.currentGrid;
            currentChBase(startSlot:end) = ...
                P.currentChargeBase;
            currentDisBase(startSlot:end) = ...
                P.currentDischargeBase;
            oneInc = sum(max(P.currentGrid -g0(startSlot:end), 0));
            oneDec = sum(max(g0(startSlot:end) -P.currentGrid, 0));
            logRow = ...
                table( ...
                thisDate, ...
                hIssue, ...
                wNow, ...
                mean(price24), ...
                S.nSelected, ...
                S.meanDistance, ...
                sum( ...
                abs( ...
                P.currentGrid-oldPlan) ...
                >1e-6), ...
                oneInc, ...
                oneDec, ...
                P.objective, ...
                P.maxConstraintViolation, ...
                'VariableNames',{ ...
                'Date', ...
                'IssueHour', ...
                'PVBlendWeight', ...
                'ForecastPriceMean', ...
                'SimilarCount', ...
                'SimilarMeanDistance', ...
                'ChangedSlots', ...
                'IncreaseVs0_kWh', ...
                'DecreaseVs0_kWh', ...
                'RollingObjective', ...
                'MaxConstraintViolation'} ...
                );
            adjustmentTable = [adjustmentTable;logRow];
        end

% 14.9 实际执行未来6h
        % 从基础储能轨迹开始，再利用当前真实误差进行反馈

        A = ...
            replayActualBlockWithBase( ...
            loadAll(dFull,blockSlots)', ...
            pvAll(dFull,blockSlots)', ...
            currentPlan(blockSlots), ...
            currentChBase(blockSlots), ...
            currentDisBase(blockSlots), ...
            Ecurrent, ...
            blockSlots, ...
            forceFinalToday, ...
            Efinal, ...
            eta, ...
            Emin, ...
            Emax, ...
            Wmax);
        executedPlan(kd,blockSlots) = ...
            currentPlan(blockSlots)';
        baseChargePlan(kd,blockSlots) = ...
            currentChBase(blockSlots)';
        baseDischargePlan(kd,blockSlots) = ...
            currentDisBase(blockSlots)';
        actualCharge(kd,blockSlots) = ...
            A.Wch';
        actualDischarge(kd,blockSlots) = ...
            A.Wdis';
        actualEmergency(kd,blockSlots) = ...
            A.Wem';
        actualSurplus(kd,blockSlots) = ...
            A.Wsur';
        Ecurrent = A.Eend;
    end

% 14.10 日末SOC

    SOCend(kd) = ...
        Ecurrent;

% 14.11 使用附件4真实价格进行正式结算

    inc = max(executedPlan(kd,:)' -g0, 0);
    dec = max(g0 -executedPlan(kd,:)', 0);
    retainedPlanCostDay(kd) = ...
        sum( ...
        actualPriceDay ...
        .*min( ...
        g0, ...
        executedPlan(kd,:)'));
    increaseCostDay(kd) = ...
        1.5 ...
        *sum( ...
        actualPriceDay ...
        .*inc);
    decreasePenaltyDay(kd) = ...
        0.5 ...
        *sum( ...
        actualPriceDay ...
        .*dec);
    emergencyCostDay(kd) = ...
        5 ...
        *sum( ...
        actualPriceDay ...
        .*actualEmergency(kd,:)');
    increaseEnergyDay(kd) = ...
        sum(inc);
    decreaseEnergyDay(kd) = ...
        sum(dec);
end
runtimeMin = toc(timerAll)/60;

%% 结果统计

dailyCost = retainedPlanCostDay +increaseCostDay +decreasePenaltyDay +emergencyCostDay;
