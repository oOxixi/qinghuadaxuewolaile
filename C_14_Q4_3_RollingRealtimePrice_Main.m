function Rlib = buildSimilarResidualLibraryQ2( ...
    F, ...
    loadAll, ...
    pvAll, ...
    predLoad, ...
    predDates, ...
    dateAll, ...
    PVlib, ...
    blendWindow, ...
    blendMinHistory)
