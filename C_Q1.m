%% ============================================================
% 2026 数模 C题 问题1
% 微网全天计划购电策略
%
% 模型：
% 基于线性规划的微网日前购电与储能协同调度模型
%
% 时间定义：
% 0:00 时刻的数据 -> 0:00-0:10
% 0:10 时刻的数据 -> 0:10-0:20
% ...
% 23:50 时刻的数据 -> 23:50-24:00
%
% 附件1原顺序：
% 0:10, 0:20, ..., 23:50, 0:00+1
%
% 问题1假设每天情况相同，因此：
% 当天0:00数据 = 下一天0:00+1数据
%
% 所以先循环移位为：
% 0:00, 0:10, ..., 23:50
%% ============================================================

clear;
clc;
close all;

fprintf('============================================\n');
fprintf(' 2026 C题 问题1：微网全天计划购电优化\n');
fprintf('============================================\n\n');


%% ============================================================
% 1. 读取附件1
%% ============================================================

filename = '附件1.xlsx';

T = readtable( ...
    filename, ...
    'VariableNamingRule','preserve');

% 附件1：
% 第1列 时间
% 第2列 电价 price（元/kWh）
% 第3列 小区负载功率（kW）
% 第4列 光伏预测功率（kW）

time_raw_original = T{:,1};

price_raw = T{:,2};
Pload_raw = T{:,3};
Pv_raw    = T{:,4};

price_raw = price_raw(:);
Pload_raw = Pload_raw(:);
Pv_raw    = Pv_raw(:);

N = length(price_raw);

fprintf('附件原始数据共有 %d 个10分钟时段。\n',N);

if N ~= 144
    error('附件1不是144个10分钟时段，请检查数据读取范围！');
end


%% ============================================================
% 2. 修正时间顺序
%
% 原顺序：
% 0:10, 0:20, ..., 23:50, 0:00+1
%
% 改成：
% 0:00, 0:10, ..., 23:50
%% ============================================================

price = [price_raw(end); price_raw(1:end-1)];

Pload = [Pload_raw(end); Pload_raw(1:end-1)];

Pv = [Pv_raw(end); Pv_raw(1:end-1)];

fprintf('时间轴已循环移位：\n');
fprintf('模型内部第1个时段 = 0:00-0:10\n');
fprintf('模型内部第144个时段 = 23:50-24:00\n\n');


%% ============================================================
% 3. 功率转电量
%% ============================================================

% 每个时间段10分钟
dt = 10/60;      % h

Wload = Pload * dt;     % kWh
Wv    = Pv * dt;        % kWh


%% ============================================================
% 4. 储能参数
%% ============================================================

eta = 0.90;

E0   = 6000;     % kWh
Emin = 1200;     % kWh
Emax = 10800;    % kWh

Pmax = 5000;     % kW

% 每10分钟最大充放电量
Wmax = Pmax * dt;

fprintf('每10分钟最大充放电量 = %.4f kWh\n\n',Wmax);


%% ============================================================
% 5. 决策变量
%
% x =
%
% [Wgrid]
% [Wch]
% [Wdis]
% [Wcut]
% [E]
%
% Wgrid : N
% Wch   : N
% Wdis  : N
% Wcut  : N
% E     : N+1
%% ============================================================

idx_grid = 1:N;

idx_ch = N + (1:N);

idx_dis = 2*N + (1:N);

idx_cut = 3*N + (1:N);

idx_E = 4*N + (1:N+1);

nvar = 5*N + 1;


%% ============================================================
% 6. 目标函数
%
% min sum(price .* Wgrid)
%% ============================================================

f = zeros(nvar,1);

f(idx_grid) = price;


%% ============================================================
% 7. 等式约束
%
% N个电量平衡方程
% N个储能动态方程
% 1个初始储电量约束
% 1个最终储电量约束
%% ============================================================

Aeq = zeros(2*N+2,nvar);

beq = zeros(2*N+2,1);


%% ============================================================
% 7.1 电量平衡
%
% Wv + Wgrid + Wdis
% =
% Wload + Wch + Wcut
%
% 整理：
%
% Wgrid - Wch + Wdis - Wcut
% =
% Wload - Wv
%% ============================================================

for t = 1:N

    Aeq(t,idx_grid(t)) = 1;

    Aeq(t,idx_ch(t)) = -1;

    Aeq(t,idx_dis(t)) = 1;

    Aeq(t,idx_cut(t)) = -1;

    beq(t) = Wload(t) - Wv(t);

end


%% ============================================================
% 7.2 储能动态
%
% E(t+1)
% =
% E(t) + eta*Wch - Wdis/eta
%
% 整理：
%
% E(t+1) - E(t) - eta*Wch + Wdis/eta = 0
%% ============================================================

for t = 1:N

    row = N + t;

    Aeq(row,idx_E(t)) = -1;

    Aeq(row,idx_E(t+1)) = 1;

    Aeq(row,idx_ch(t)) = -eta;

    Aeq(row,idx_dis(t)) = 1/eta;

    beq(row) = 0;

end


%% ============================================================
% 7.3 初始储电量
%% ============================================================

Aeq(2*N+1,idx_E(1)) = 1;

beq(2*N+1) = E0;


%% ============================================================
% 7.4 24:00储电量
%% ============================================================

Aeq(2*N+2,idx_E(end)) = 1;

beq(2*N+2) = E0;


%% ============================================================
% 8. 不等式约束
%% ============================================================

A = [];

b = [];


%% ============================================================
% 9. 变量上下界
%% ============================================================

lb = zeros(nvar,1);

ub = inf(nvar,1);


% ---------- 外网购电 ----------
lb(idx_grid) = 0;


% ---------- 储能充电 ----------
lb(idx_ch) = 0;

ub(idx_ch) = Wmax;


% ---------- 储能放电 ----------
lb(idx_dis) = 0;

ub(idx_dis) = Wmax;


% ---------- 弃光 ----------
lb(idx_cut) = 0;


% ---------- 储能电量 ----------
lb(idx_E) = Emin;

ub(idx_E) = Emax;


%% ============================================================
% 10. 求解线性规划
%
% 明确使用 HiGHS 双单纯形法
%% ============================================================

options = optimoptions( ...
    'linprog', ...
    'Algorithm','dual-simplex-highs', ...
    'Display','iter');


[x,fval,exitflag,output] = linprog( ...
    f, ...
    A, ...
    b, ...
    Aeq, ...
    beq, ...
    lb, ...
    ub, ...
    options);


if exitflag <= 0

    error('优化失败，请检查数据和模型！');

end


fprintf('\n============================================\n');
fprintf('问题1优化成功！\n');
fprintf('求解算法：HiGHS 双单纯形法\n');
fprintf('============================================\n');


%% ============================================================
% 11. 提取优化结果
%% ============================================================

Wgrid = x(idx_grid);

Wch = x(idx_ch);

Wdis = x(idx_dis);

Wcut = x(idx_cut);

E = x(idx_E);


%% ============================================================
% 12. 全天结果
%% ============================================================

total_grid = sum(Wgrid);

total_cost = sum(price .* Wgrid);

total_cut = sum(Wcut);


fprintf('\n========== 全天优化结果 ==========\n');

fprintf('全天购电量 = %.4f kWh\n',total_grid);

fprintf('全天购电费 = %.4f 元\n',total_cost);

fprintf('全天弃光量 = %.4f kWh\n',total_cut);

fprintf('\n');

fprintf('0:00储电量  = %.4f kWh\n',E(1));

fprintf('24:00储电量 = %.4f kWh\n',E(end));

fprintf('最低储电量  = %.4f kWh\n',min(E));

fprintf('最高储电量  = %.4f kWh\n',max(E));


%% ============================================================
% 13. 电量平衡检查
%% ============================================================

balance_error = ...
    Wv + Wgrid + Wdis ...
    - Wload - Wch - Wcut;


fprintf('\n最大电量平衡误差 = %.12f kWh\n', ...
    max(abs(balance_error)));


%% ============================================================
% 14. 检查是否同时充放电
%% ============================================================

simultaneous_idx = ...
    find(Wch > 1e-6 & Wdis > 1e-6);

fprintf('\n同时充放电时段数 = %d\n', ...
    length(simultaneous_idx));

if isempty(simultaneous_idx)

    fprintf('未出现明显同时充放电现象。\n');

else

    fprintf('警告：存在同时充放电时段，请进一步检查。\n');

end


%% ============================================================
% 15. 表1：指定时间段购电量
%
% 当前内部时间：
%
% Wgrid(1)  = 0:00-0:10
% Wgrid(61) = 10:00-10:10
%
% 所以：
% index = hour*6 + 1
%% ============================================================

hours_select = [10 12 14 16 18 20];

idx_select = hours_select*6 + 1;


fprintf('\n============================================\n');
fprintf('表1 指定时段计划购电量\n');
fprintf('============================================\n');


for i = 1:length(hours_select)

    t = idx_select(i);

    fprintf('%02d:00-%02d:10：%.4f kWh\n', ...
        hours_select(i), ...
        hours_select(i), ...
        Wgrid(t));

end


fprintf('\n全天购电量：%.4f kWh\n',total_grid);

fprintf('全天购电费：%.4f 元\n',total_cost);


%% ============================================================
% 16. 表2：每4小时充放电量
%
% 当前内部顺序已经从0:00开始：
%
% 1:24     -> 0:00-4:00
% 25:48    -> 4:00-8:00
% ...
% 121:144  -> 20:00-24:00
%% ============================================================

charge4h = zeros(6,1);

discharge4h = zeros(6,1);


fprintf('\n============================================\n');
fprintf('表2 储能充放电量\n');
fprintf('============================================\n');


for k = 1:6

    i1 = (k-1)*24 + 1;

    i2 = k*24;


    charge4h(k) = ...
        sum(Wch(i1:i2));

    discharge4h(k) = ...
        sum(Wdis(i1:i2));


    fprintf('%02d:00-%02d:00：充电 %.4f kWh，放电 %.4f kWh\n', ...
        (k-1)*4, ...
        k*4, ...
        charge4h(k), ...
        discharge4h(k));

end


fprintf('\n0:00储电量  = %.4f kWh\n',E(1));

fprintf('24:00储电量 = %.4f kWh\n',E(end));


%% ============================================================
% 17. 时间轴
%
% 第1个数据点对应0:00
% 第144个数据点对应23:50
%% ============================================================

time_h = (0:N-1)' * dt;

time_E = (0:N)' * dt;


%% ============================================================
% 18. 绘图：外网购电
%% ============================================================

figure;

plot( ...
    time_h, ...
    Wgrid, ...
    'LineWidth',1.5);

xlabel('时间 / h');

ylabel('购电量 / kWh');

title('全天计划购电量');

xlim([0 24]);

grid on;


%% ============================================================
% 19. 绘图：储能充放电
%% ============================================================

figure;

plot( ...
    time_h, ...
    Wch, ...
    'LineWidth',1.5);

hold on;

plot( ...
    time_h, ...
    Wdis, ...
    'LineWidth',1.5);


xlabel('时间 / h');

ylabel('电量 / kWh');

legend( ...
    '充电量 Wch', ...
    '放电量 Wdis', ...
    'Location','best');

title('储能充放电策略');

xlim([0 24]);

grid on;


%% ============================================================
% 20. 绘图：储能SOC
%% ============================================================

figure;

plot( ...
    time_E, ...
    E, ...
    'LineWidth',1.5);


xlabel('时间 / h');

ylabel('储电量 / kWh');

title('储能设备电量变化');

xlim([0 24]);

grid on;


%% ============================================================
% 21. 绘图：弃光量
%% ============================================================

figure;

plot( ...
    time_h, ...
    Wcut, ...
    'LineWidth',1.5);


xlabel('时间 / h');

ylabel('弃光量 / kWh');

title('光伏弃光量');

xlim([0 24]);

grid on;


%% ============================================================
% 22. 输出官方 result1.xlsx
%
% 注意：
%
% 模型内部：
% 0:00-0:10
% 0:10-0:20
% ...
% 23:50-24:00
%
% 官方模板：
% 0:10-0:20
% ...
% 23:50-0:00+1
% 0:00+1-0:10+1
%
% 因此写回模板前，再循环移位一次。
%% ============================================================

outputFile = ...
    'E:\数模\2026年正式比赛\CUMCM2026Problems\C题\附件\附件5\result1.xlsx';


%% ------------------------------------------------------------
% 22.1 恢复官方模板购电量顺序
%% ------------------------------------------------------------

Wgrid_output = ...
    [Wgrid(2:end); Wgrid(1)];


if length(Wgrid_output) ~= 144

    error('Wgrid_output数量不是144，请检查！');

end


%% ------------------------------------------------------------
% 22.2 写入144个10分钟购电量
%% ------------------------------------------------------------

writematrix( ...
    Wgrid_output, ...
    outputFile, ...
    'Sheet','计划购电量', ...
    'Range','B2');


%% ------------------------------------------------------------
% 22.3 写入6个4小时充放电量
%
% 官方充放电量表按：
% 0:00-4:00
% 4:00-8:00
% ...
% 20:00-24:00
%
% 所以这里直接使用内部正确汇总结果即可。
%% ------------------------------------------------------------

writematrix( ...
    charge4h, ...
    outputFile, ...
    'Sheet','充放电量', ...
    'Range','B2');


writematrix( ...
    discharge4h, ...
    outputFile, ...
    'Sheet','充放电量', ...
    'Range','C2');


%% ------------------------------------------------------------
% 22.4 写入0:00与24:00储电量
%% ------------------------------------------------------------

writematrix( ...
    E(1), ...
    outputFile, ...
    'Sheet','充放电量', ...
    'Range','E2');


writematrix( ...
    E(end), ...
    outputFile, ...
    'Sheet','充放电量', ...
    'Range','E3');


%% ------------------------------------------------------------
% 22.5 输出检查
%% ------------------------------------------------------------

fprintf('\n============================================\n');
fprintf('result1.xlsx 已写入完成！\n');
fprintf('============================================\n');

fprintf('文件位置：\n%s\n',outputFile);

fprintf('\n');

fprintf('写入计划购电量数量：%d\n', ...
    length(Wgrid_output));

fprintf('0:00储电量：%.4f kWh\n', ...
    E(1));

fprintf('24:00储电量：%.4f kWh\n', ...
    E(end));


fprintf('\n六个4小时时段充放电量：\n');


for k = 1:6

    fprintf( ...
        '%02d:00-%02d:00：充电 %.4f kWh，放电 %.4f kWh\n', ...
        (k-1)*4, ...
        k*4, ...
        charge4h(k), ...
        discharge4h(k));

end


%% ============================================================
% 23. 导出论文绘图数据
%% ============================================================

% 无储能优化情况下的直接购电需求
baseline_grid = ...
    max(Wload - Wv,0);


storage_start = ...
    E(1:N);

storage_end = ...
    E(2:N+1);


plotData = table( ...
    time_h, ...
    price, ...
    Wload, ...
    Wv, ...
    baseline_grid, ...
    Wgrid, ...
    Wch, ...
    Wdis, ...
    Wcut, ...
    storage_start, ...
    storage_end, ...
    'VariableNames',{ ...
    'time_h', ...
    'price', ...
    'load_energy', ...
    'pv_energy', ...
    'baseline_grid', ...
    'grid_energy', ...
    'charge_energy', ...
    'discharge_energy', ...
    'cut_energy', ...
    'storage_start', ...
    'storage_end'});


outputPlotFile = ...
    'E:\数模\2026年正式比赛\CUMCM2026Problems\C题\Q1_plot_data.xlsx';


writetable( ...
    plotData, ...
    outputPlotFile);


fprintf('\n论文绘图数据已保存：\n%s\n', ...
    outputPlotFile);


