fprintf('Wgrid(2)   -> 0:10-0:20\n');

fprintf('Wgrid(61)  -> 10:00-10:10\n');

fprintf('Wgrid(144) -> 23:50-24:00\n');

fprintf('\n');

fprintf('官方结果表第1行 <- Wgrid(2)：0:10-0:20\n');

fprintf('官方结果表最后1行 <- Wgrid(1)：次日0:00-0:10\n');

fprintf('============================================\n');