fprintf('计算Q0.8滚动风险校准...\n');


q80Correction = ...
    zeros(nDay,nTime);


calibrationActive = ...
    false(nDay,1);


historyDaysUsed = ...
    zeros(nDay,1);


for d = 1:nDay

    histEnd = ...
        d-1;


    histStart = ...
        max( ...
        1, ...
        d-ROLLING_WINDOW_DAYS);


    if histEnd<histStart

        continue;

    end


    nHist = ...
        histEnd-histStart+1;


    historyDaysUsed(d) = ...
        nHist;


    if nHist<MIN_HISTORY_DAYS

        continue;

    end


    calibrationActive(d) = ...
        true;


    for t = 1:nTime

        r = ...
            residualNet( ...
            histStart:histEnd, ...
            t);


        r = ...
            r(isfinite(r));


        if length(r)>=MIN_HISTORY_DAYS

            q80Correction(d,t) = ...
                quantile( ...
                r, ...
                Q_LEVEL);

        end

    end

end


correctedNet = ...
    forecastNet ...
    +q80Correction;


