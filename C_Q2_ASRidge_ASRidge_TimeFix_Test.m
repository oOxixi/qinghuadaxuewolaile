%% ============================================================
% 局部函数1：
% 日前计划LP
%% ============================================================

function plan = solveDailyPlanTerminalSOC( ...
    Pload, ...
    Pv, ...
    price, ...
    Estart, ...
    terminalLow, ...
    terminalHigh, ...
    dt, ...
    eta_ch, ...
    eta_dis, ...
    Emin, ...
    Emax, ...
    Wmax, ...
    cyclePenalty, ...
    curtailPenalty, ...
    options)


N = ...
    length(price);


Wload = ...
    Pload(:)*dt;


Wpv = ...
    Pv(:)*dt;


price = ...
    price(:);


%% 变量

idxGrid = ...
    1:N;


idxCh = ...
    N+(1:N);


idxDis = ...
    2*N+(1:N);


idxCut = ...
    3*N+(1:N);


idxE = ...
    4*N+(1:N+1);


nVar = ...
    5*N+1;


%% 目标函数

f = ...
    zeros(nVar,1);


f(idxGrid) = ...
    price;


f(idxCh) = ...
    cyclePenalty;


f(idxDis) = ...
    cyclePenalty;


f(idxCut) = ...
    curtailPenalty;


%% 等式约束

Aeq = ...
    zeros( ...
    2*N+1, ...
    nVar);


beq = ...
    zeros( ...
    2*N+1, ...
    1);


% ------------------------------------------------------------
% 电量平衡
%
% grid + PV + discharge
% =
% load + charge + curtail
% ------------------------------------------------------------

for t = 1:N

    Aeq(t,idxGrid(t)) = ...
        1;


    Aeq(t,idxCh(t)) = ...
        -1;


    Aeq(t,idxDis(t)) = ...
        1;


    Aeq(t,idxCut(t)) = ...
        -1;


    beq(t) = ...
        Wload(t) ...
        -Wpv(t);

end


% ------------------------------------------------------------
% SOC
% ------------------------------------------------------------

for t = 1:N

    r = ...
        N+t;


    Aeq(r,idxE(t)) = ...
        -1;


    Aeq(r,idxE(t+1)) = ...
        1;


    Aeq(r,idxCh(t)) = ...
        -eta_ch;


    Aeq(r,idxDis(t)) = ...
        1/eta_dis;

end


% 日初SOC
Aeq(2*N+1,idxE(1)) = ...
    1;


beq(2*N+1) = ...
    Estart;


%% 上下界

lb = ...
    zeros(nVar,1);


ub = ...
    inf(nVar,1);


% 单时段最大充电
ub(idxCh) = ...
    Wmax;


% 单时段最大放电
ub(idxDis) = ...
    Wmax;


% 弃光上限
ub(idxCut) = ...
    Wpv;


% SOC
lb(idxE) = ...
    Emin;


ub(idxE) = ...
    Emax;


lb(idxE(end)) = ...
    terminalLow;


ub(idxE(end)) = ...
    terminalHigh;


%% 求解

[x,~,exitflag,output] = ...
    linprog( ...
    f, ...
    [],[], ...
    Aeq,beq, ...
    lb,ub, ...
    options);


if exitflag<=0

    error( ...
        '计划LP失败：%s', ...
        output.message);

end


plan.Wgrid = ...
    x(idxGrid);


plan.Wch = ...
    x(idxCh);


plan.Wdis = ...
    x(idxDis);


plan.Wcut = ...
    x(idxCut);


plan.E = ...
    x(idxE);

end


%% ============================================================
% 局部函数2：
% 实际逐10min严格因果执行
%
% 允许同时充放电
%% ============================================================

function replay = replayActualDayCausalAllowSimultaneous( ...
    Pload, ...
    Pv, ...
    Wgrid, ...
    WchPlan, ...
    WdisPlan, ...
    Estart, ...
    dt, ...
    eta_ch, ...
    eta_dis, ...
    Emin, ...
    Emax, ...
    Wmax, ...
    forceFinalSOC, ...
    EfinalTarget)


N = ...
    length(Wgrid);


Wload = ...
    Pload(:)*dt;


Wpv = ...
    Pv(:)*dt;


Wgrid = ...
    Wgrid(:);


WchPlan = ...
    WchPlan(:);


WdisPlan = ...
    WdisPlan(:);


Wch = ...
    zeros(N,1);


Wdis = ...
    zeros(N,1);


Wspill = ...
    zeros(N,1);


Wem = ...
    zeros(N,1);


E = ...
    zeros(N+1,1);


E(1) = ...
    Estart;


for t = 1:N

    Ecurrent = ...
        E(t);


    %% --------------------------------------------------------
    % 下一时刻SOC允许范围
    %% --------------------------------------------------------

    EnextLow = ...
        Emin;


    EnextHigh = ...
        Emax;


    %% --------------------------------------------------------
    % 如果最后一天强制SOC=6000，
    % 仅通过可达区间限制当前SOC
    %% --------------------------------------------------------

    if forceFinalSOC

        remainingSlots = ...
            N-t;


        reachLow = ...
            EfinalTarget ...
            -remainingSlots ...
            *eta_ch ...
            *Wmax;


        reachHigh = ...
            EfinalTarget ...
            +remainingSlots ...
            *Wmax/eta_dis;


        EnextLow = ...
            max( ...
            Emin, ...
            reachLow);


        EnextHigh = ...
            min( ...
            Emax, ...
            reachHigh);


        if EnextLow>EnextHigh+1e-7

            error( ...
                '终端SOC不可达：t=%d', ...
                t);

        end

    end


    %% --------------------------------------------------------
    % 先保留计划充放电动作
    %% --------------------------------------------------------

    WchNow = ...
        min( ...
        max(WchPlan(t),0), ...
        Wmax);


    WdisNow = ...
        min( ...
        max(WdisPlan(t),0), ...
        Wmax);


    EnextCandidate = ...
        Ecurrent ...
        +eta_ch*WchNow ...
        -WdisNow/eta_dis;


    %% --------------------------------------------------------
    % 先确保计划动作本身不会造成SOC越界
    %% --------------------------------------------------------

    if EnextCandidate<EnextLow

        needSOC = ...
            EnextLow ...
            -EnextCandidate;


        reduceDis = ...
            min( ...
            WdisNow, ...
            needSOC*eta_dis);


        WdisNow = ...
            WdisNow ...
            -reduceDis;


        EnextCandidate = ...
            Ecurrent ...
            +eta_ch*WchNow ...
            -WdisNow/eta_dis;


        if EnextCandidate<EnextLow-1e-10

            addCh = ...
                min( ...
                Wmax-WchNow, ...
                (EnextLow-EnextCandidate)/eta_ch);


            WchNow = ...
                WchNow ...
                +addCh;


            EnextCandidate = ...
                Ecurrent ...
                +eta_ch*WchNow ...
                -WdisNow/eta_dis;

        end

    end


    if EnextCandidate>EnextHigh

        needSOC = ...
            EnextCandidate ...
            -EnextHigh;


        reduceCh = ...
            min( ...
            WchNow, ...
            needSOC/eta_ch);


        WchNow = ...
            WchNow ...
            -reduceCh;


        EnextCandidate = ...
            Ecurrent ...
            +eta_ch*WchNow ...
            -WdisNow/eta_dis;


        if EnextCandidate>EnextHigh+1e-10

            addDis = ...
                min( ...
                Wmax-WdisNow, ...
                (EnextCandidate-EnextHigh)*eta_dis);


            WdisNow = ...
                WdisNow ...
                +addDis;


            EnextCandidate = ...
                Ecurrent ...
                +eta_ch*WchNow ...
                -WdisNow/eta_dis;

        end

    end


    %% --------------------------------------------------------
    % 当前真实供需相对计划储能动作的残差
    %
    % 正值 = 缺电
    % 负值 = 富余
    %% --------------------------------------------------------

    batteryNet = ...
        WdisNow ...
        -WchNow;


    requiredBatteryNet = ...
        Wload(t) ...
        -Wpv(t) ...
        -Wgrid(t);


    residual = ...
        requiredBatteryNet ...
        -batteryNet;


    %% ========================================================
    % 缺电
    %% ========================================================

    if residual>1e-12

        % -----------------------------------------------------
        % 1. 先减少当前充电
        % -----------------------------------------------------

        maxReduceChargeSOC = ...
            max( ...
            (EnextCandidate-EnextLow)/eta_ch, ...
            0);


        reduceCharge = ...
            min( ...
            [ ...
            residual, ...
            WchNow, ...
            maxReduceChargeSOC ...
            ]);


        WchNow = ...
            WchNow ...
            -reduceCharge;


        residual = ...
            residual ...
            -reduceCharge;


        EnextCandidate = ...
            EnextCandidate ...
            -eta_ch*reduceCharge;


        % -----------------------------------------------------
        % 2. 再增加放电
        % -----------------------------------------------------

        if residual>1e-12

            maxExtraDisSOC = ...
                eta_dis ...
                *max( ...
                EnextCandidate-EnextLow, ...
                0);


            maxExtraDis = ...
                min( ...
                Wmax-WdisNow, ...
                maxExtraDisSOC);


            extraDis = ...
                min( ...
                residual, ...
                maxExtraDis);


            WdisNow = ...
                WdisNow ...
                +extraDis;


            residual = ...
                residual ...
                -extraDis;


            EnextCandidate = ...
                EnextCandidate ...
                -extraDis/eta_dis;

        end


        % -----------------------------------------------------
        % 3. 剩余缺口紧急购电
        % -----------------------------------------------------

        Wem(t) = ...
            max( ...
            residual, ...
            0);


        Wspill(t) = ...
            0;


    %% ========================================================
    % 富余
    %% ========================================================

    elseif residual<-1e-12

        surplus = ...
            -residual;


        % -----------------------------------------------------
        % 1. 先减少当前放电
        % -----------------------------------------------------

        maxReduceDisSOC = ...
            eta_dis ...
            *max( ...
            EnextHigh-EnextCandidate, ...
            0);


        reduceDis = ...
            min( ...
            [ ...
            surplus, ...
            WdisNow, ...
            maxReduceDisSOC ...
            ]);


        WdisNow = ...
            WdisNow ...
            -reduceDis;


        surplus = ...
            surplus ...
            -reduceDis;


        EnextCandidate = ...
            EnextCandidate ...
            +reduceDis/eta_dis;


        % -----------------------------------------------------
        % 2. 再增加充电
        % -----------------------------------------------------

        if surplus>1e-12

            maxExtraChargeSOC = ...
                max( ...
                EnextHigh-EnextCandidate, ...
                0) ...
                /eta_ch;


            maxExtraCharge = ...
                min( ...
                Wmax-WchNow, ...
                maxExtraChargeSOC);


            extraCharge = ...
                min( ...
                surplus, ...
                maxExtraCharge);


            WchNow = ...
                WchNow ...
                +extraCharge;


            surplus = ...
                surplus ...
                -extraCharge;


            EnextCandidate = ...
                EnextCandidate ...
                +eta_ch*extraCharge;

        end


        % -----------------------------------------------------
        % 3. 剩余记为实际未利用富余电量
        % -----------------------------------------------------

        Wspill(t) = ...
            max( ...
            surplus, ...
            0);


        Wem(t) = ...
            0;


    else

        Wem(t) = ...
            0;


        Wspill(t) = ...
            0;

    end


    %% --------------------------------------------------------
    % 保存
    %% --------------------------------------------------------

    Wch(t) = ...
        WchNow;


    Wdis(t) = ...
        WdisNow;


    E(t+1) = ...
        Ecurrent ...
        +eta_ch*Wch(t) ...
        -Wdis(t)/eta_dis;


    if abs(E(t+1)-Emin)<1e-9

        E(t+1) = ...
            Emin;

    end


    if abs(E(t+1)-Emax)<1e-9

        E(t+1) = ...
            Emax;

    end


    if E(t+1)<EnextLow-1e-6 ...
            || E(t+1)>EnextHigh+1e-6

        error( ...
            ['实际回放SOC越界：', ...
             't=%d, E=%.6f, 合法范围=[%.6f,%.6f]'], ...
            t, ...
            E(t+1), ...
            EnextLow, ...
            EnextHigh);

    end

end


if forceFinalSOC ...
        && abs(E(end)-EfinalTarget)>1e-4

    error( ...
        '最终SOC未达到目标：%.6f', ...
        E(end));

end


replay.Wch = ...
    Wch;


replay.Wdis = ...
    Wdis;


replay.Wspill = ...
    Wspill;


replay.Wem = ...
    Wem;


replay.E = ...
    E;


replay.Eend = ...
    E(end);

end
%% ============================================================
% 辅助函数1：根据表头文字寻找Excel列号
%% ============================================================

function col = findHeaderColumn(C,keywords)

col = [];

[nr,nc] = size(C);

for j = 1:nc

    txt = "";

    for i = 1:nr

        one = ...
            string(C{i,j});

        if ~ismissing(one)

            txt = ...
                txt + one;

        end

    end

    txt = ...
        replace( ...
        txt, ...
        " ", ...
        "");


    for k = 1:length(keywords)

        if contains( ...
                txt, ...
                string(keywords{k}))

            col = ...
                j;

            return;

        end

    end

end

end


