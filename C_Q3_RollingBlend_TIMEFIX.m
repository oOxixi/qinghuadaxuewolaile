    history(good);


actual = ...
    actual(good);


den = ...
    sum( ...
    (formal-history).^2);


if isempty(actual) ...
        || den<1e-12

    w = ...
        1;


    return;

end


w = ...
    sum( ...
    (actual-history) ...
    .*(formal-history)) ...
    /den;


w = ...
    min( ...
    max(w,0), ...
    1);

end


