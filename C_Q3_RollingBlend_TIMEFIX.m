    options)


[H,nScenario] = ...
    size(PloadScenario);


if H~=144 ...
        || ~isequal( ...
        size(PpvScenario), ...
        [H,nScenario])

    error( ...
        '场景必须为144×S。');

end


prob = ...
    prob(:);


prob = ...
    prob/sum(prob);


price24 = ...
    price24(:);


nextN = ...
    H-qCurrent;


isInitial = ...
    isempty(g0Remain);


iCurrent = ...
    1:qCurrent;


if isInitial

    commonN = ...
        qCurrent;


    iInc = ...
        [];


    iDec = ...
        [];

else

    iInc = ...
        qCurrent+(1:qCurrent);


    iDec = ...
        2*qCurrent+(1:qCurrent);


    commonN = ...
        3*qCurrent;


    g0Remain = ...
        g0Remain(:);

end


scenarioBlock = ...
    nextN ...
    +5*H ...
    +1;


nVar = ...
    commonN ...
    +nScenario*scenarioBlock;


f = ...
    zeros(nVar,1);


f(iCurrent) = ...
    price24(1:qCurrent);


if ~isInitial

    f(iInc) = ...
        0.5 ...
        *price24(1:qCurrent);


    f(iDec) = ...
        0.5 ...
        *price24(1:qCurrent);

end


lb = ...
    zeros(nVar,1);


ub = ...
    inf(nVar,1);


nDeviationEq = ...
    double(~isInitial) ...
    *qCurrent;


nEq = ...
    nDeviationEq ...
    +nScenario*(2*H+1);


Aeq = ...
    spalloc( ...
    nEq, ...
    nVar, ...
    max( ...
    1, ...
    nDeviationEq*3 ...
    +nScenario*(10*H+2)));


beq = ...
    zeros(nEq,1);


row = ...
    0;


if ~isInitial

    for t = 1:qCurrent

        row = ...
            row+1;


        Aeq(row,iCurrent(t)) = ...
            1;


        Aeq(row,iInc(t)) = ...
            -1;


        Aeq(row,iDec(t)) = ...
            1;


        beq(row) = ...
            g0Remain(t);

    end


    ub(iDec) = ...
        g0Remain;

end


for s = 1:nScenario

    base = ...
        commonN ...
        +(s-1)*scenarioBlock;


    iNext = ...
        base+(1:nextN);


    iCh = ...
        base+nextN+(1:H);


    iDis = ...
        base+nextN+H+(1:H);


    iSur = ...
        base+nextN+2*H+(1:H);


    iEm = ...
        base+nextN+3*H+(1:H);


    iE = ...
        base+nextN+4*H+(1:H+1);


    if nextN>0

        f(iNext) = ...
            prob(s) ...
            *price24(qCurrent+1:end);

    end


    f(iEm) = ...
        prob(s) ...
        *5 ...
        *price24;


    f(iCh) = ...
        prob(s) ...
        *cyclePenalty;


    f(iDis) = ...
        prob(s) ...
        *cyclePenalty;


    f(iSur) = ...
        prob(s) ...
        *curtailPenalty;


    f(iE(end)) = ...
        f(iE(end)) ...
        -prob(s)*terminalValue;


    ub(iCh) = ...
        Wmax;


    ub(iDis) = ...
        Wmax;


    lb(iE) = ...
        Emin;


    ub(iE) = ...
        Emax;


    if forceFinalToday

        midnightState = ...
            iE(qCurrent+1);


        lb(midnightState) = ...
            Efinal;


        ub(midnightState) = ...
            Efinal;

    end


    Wload = ...
        PloadScenario(:,s)*dt;


    Wpv = ...
        PpvScenario(:,s)*dt;


    for t = 1:H

        row = ...
            row+1;


        if t<=qCurrent

            iGrid = ...
                iCurrent(t);

        else

            iGrid = ...
                iNext(t-qCurrent);

        end


        Aeq(row,iGrid) = ...
            1;


        Aeq(row,iDis(t)) = ...
            1;


        Aeq(row,iEm(t)) = ...
            1;


        Aeq(row,iCh(t)) = ...
            -1;


        Aeq(row,iSur(t)) = ...
            -1;


        beq(row) = ...
            Wload(t) ...
            -Wpv(t);

    end


    for t = 1:H

        row = ...
            row+1;


        Aeq(row,iE(t)) = ...
            -1;


        Aeq(row,iE(t+1)) = ...
            1;


        Aeq(row,iCh(t)) = ...
            -eta;


        Aeq(row,iDis(t)) = ...
            1/eta;

    end


    row = ...
        row+1;


    Aeq(row,iE(1)) = ...
        1;


    beq(row) = ...
        Estart;

end


[x,fval,exitflag,output] = ...
    linprog( ...
    f, ...
    [], ...
    [], ...
    Aeq, ...
    beq, ...
    lb, ...
    ub, ...
    options);


if exitflag<=0

    error( ...
        '滚动LP失败：%s', ...
        output.message);

end


eqViolation = ...
    max( ...
    abs( ...
    Aeq*x-beq));


