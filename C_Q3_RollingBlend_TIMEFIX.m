    max( ...
    [ ...
    max(lb-x), ...
    max(x-ub), ...
    0 ...
    ]);


maxViolation = ...
    max( ...
    eqViolation, ...
    boundViolation);


P.currentGrid = ...
    x(iCurrent);


P.objective = ...
    fval;


P.exitflag = ...
    exitflag;


P.maxConstraintViolation = ...
    maxViolation;

end


%% ============================================================
% 局部函数3
% 实际严格因果执行
%% ============================================================

function A = replayActualBlock( ...
    Pload, ...
    Ppv, ...
    Wgrid, ...
    Estart, ...
    globalSlots, ...
    forceFinalToday, ...
    Efinal, ...
    dt, ...
    eta, ...
    Emin, ...
    Emax, ...
    Wmax)


Wload = ...
    Pload(:)*dt;


Wpv = ...
    Ppv(:)*dt;


Wgrid = ...
    Wgrid(:);


N = ...
    length(Wgrid);


Wch = ...
    zeros(N,1);


Wdis = ...
    zeros(N,1);


Wem = ...
    zeros(N,1);


Wsur = ...
    zeros(N,1);


E = ...
    Estart;


for j = 1:N

    tGlobal = ...
        globalSlots(j);


    if forceFinalToday

        remainingSlots = ...
            144-tGlobal;


        nextLow = ...
            max( ...
            Emin, ...
            Efinal ...
            -remainingSlots*eta*Wmax);


        nextHigh = ...
            min( ...
            Emax, ...
            Efinal ...
            +remainingSlots*Wmax/eta);

    else

        nextLow = ...
            Emin;


        nextHigh = ...
            Emax;

    end


    balance = ...
        Wpv(j) ...
        +Wgrid(j) ...
        -Wload(j);


    ch = ...
        0;


    dis = ...
        0;


    em = ...
        0;


    surplus = ...
        0;


    if balance>=0

        if E>nextHigh

            dis = ...
                min( ...
                Wmax, ...
                (E-nextHigh)*eta);


            Enew = ...
                E ...
                -dis/eta;


            surplus = ...
                balance ...
                +dis;

        else

            ch = ...
                min( ...
                [ ...
                balance, ...
                Wmax, ...
                max( ...
                (nextHigh-E)/eta, ...
                0) ...
                ]);


            Enew = ...
                E ...
                +eta*ch;


            surplus = ...
                balance ...
                -ch;


            if Enew<nextLow-1e-9

                extraCh = ...
                    min( ...
                    (nextLow-Enew)/eta, ...
                    Wmax-ch);


                ch = ...
                    ch ...
                    +extraCh;


                em = ...
                    extraCh;


                Enew = ...
                    E ...
                    +eta*ch;

            end

        end

    else

        deficit = ...
            -balance;


        if E<=nextLow

            ch = ...
                min( ...
                max( ...
                (nextLow-E)/eta, ...
                0), ...
                Wmax);


            em = ...
                deficit ...
                +ch;


            Enew = ...
                E ...
                +eta*ch;

        else

            dis = ...
                min( ...
                [ ...
                deficit, ...
                Wmax, ...
                (E-nextLow)*eta ...
                ]);


            em = ...
                deficit ...
                -dis;


            Enew = ...
                E ...
                -dis/eta;


            if Enew>nextHigh+1e-9

                extraDis = ...
                    min( ...
                    (Enew-nextHigh)*eta, ...
                    Wmax-dis);


                dis = ...
                    dis ...
                    +extraDis;


                surplus = ...
                    extraDis;


                Enew = ...
                    E ...
                    -dis/eta;

            end

        end

    end


    if Enew<nextLow-1e-5 ...
            || Enew>nextHigh+1e-5

        error( ...
            '实际回放SOC不可达。');

    end


    E = ...
        min( ...
        max( ...
        Enew, ...
        Emin), ...
        Emax);


    Wch(j) = ...
        ch;


    Wdis(j) = ...
        dis;


    Wem(j) = ...
        em;


    Wsur(j) = ...
        surplus;

end


A.Wch = ...
    Wch;


A.Wdis = ...
    Wdis;


A.Wem = ...
    Wem;


A.Wsur = ...
    Wsur;


A.Eend = ...
    E;

end


