% 运行一个策略
%% ============================================================

function R = runOneStrategy( ...
    strategyName, ...
    updateMask, ...
    freezePV, ...
    targetDays, ...
    predDates, ...
    dateAll, ...
    loadAll, ...
    pvAll, ...
    loadForecastToday, ...
    loadForecastNext, ...
    F, ...
    scenarioCache, ...
    wDynamic, ...
    price, ...
    dt, ...
    eta, ...
    Emin, ...
    Emax, ...
    Einitial, ...
    Efinal, ...
    Wmax, ...
    terminalValue, ...
    cyclePenalty, ...
    curtailPenalty, ...
    forceFinalSOC6000, ...
    lpOptions)


nDay = ...
    length(targetDays);


nTime = ...
    144;


issueHours = ...
    [0,6,12,18];


plan0 = ...
    zeros(nDay,nTime);


executedPlan = ...
    zeros(nDay,nTime);


planAfter = ...
    nan(nDay,nTime,4);


actualCharge = ...
    zeros(nDay,nTime);


actualDischarge = ...
    zeros(nDay,nTime);


actualEmergency = ...
    zeros(nDay,nTime);


actualSurplus = ...
    zeros(nDay,nTime);


SOCstart = ...
    zeros(nDay,1);


SOCend = ...
    zeros(nDay,1);


retainedPlanCostDay = ...
    zeros(nDay,1);


increaseCostDay = ...
    zeros(nDay,1);


decreasePenaltyDay = ...
    zeros(nDay,1);


emergencyCostDay = ...
    zeros(nDay,1);


increaseEnergyDay = ...
    zeros(nDay,1);


decreaseEnergyDay = ...
    zeros(nDay,1);


adjustmentTable = ...
    table();


maxLPViolation = ...
    0;


Ecurrent = ...
    Einitial;


for kd = 1:nDay

    d = ...
        targetDays(kd);


    thisDate = ...
        dateAll(d);


    isLastDay = ...
        d==365;


    forceFinalToday = ...
        isLastDay ...
        && forceFinalSOC6000;


    terminalValueToday = ...
        terminalValue;


    if isLastDay ...
            && ~forceFinalSOC6000

        terminalValueToday = ...
            0;

    end


    SOCstart(kd) = ...
        Ecurrent;


    if mod(kd-1,20)==0 ...
            || isLastDay

        fprintf( ...
            '  [%03d/%03d] %s，SOC %.2f\n', ...
            kd, ...
            nDay, ...
            string(thisDate), ...
            Ecurrent);

    end


    %% --------------------------------------------------------
    % 冻结0时预报对照
    %% --------------------------------------------------------

    w0 = ...
        wDynamic(kd,1);


    frozenPV48 = ...
        buildFrozenPV48( ...
        F, ...
        pvAll, ...
        dateAll, ...
        d, ...
        w0);


    currentPlan = ...
        zeros(nTime,1);


    g0 = ...
        zeros(nTime,1);


    for ki = 1:4

        hIssue = ...
            issueHours(ki);


        %% ----------------------------------------------------
        % ★发布时间后的第一个未来10min时段
        %
        % 0h  -> col1   = 00:10
        % 6h  -> col37  = 06:10
        % 12h -> col73  = 12:10
        % 18h -> col109 = 18:10
        %% ----------------------------------------------------

        startSlot = ...
            hIssue*6+1;


        %% 每次执行6h：
        % 0:10~6:00
        % 6:10~12:00
        % 12:10~18:00
        % 18:10~次日0:00
        endSlot = ...
            min( ...
            startSlot+35, ...
            nTime);


        shouldOptimize = ...
            ki==1 ...
            || updateMask(ki);


        if shouldOptimize

            %% ------------------------------------------------
            % 负载24h预测
            %% ------------------------------------------------

            baseLoad24 = ...
                makeLoadForecast24( ...
                loadForecastToday, ...
                loadForecastNext, ...
                d, ...
                hIssue);


            %% ------------------------------------------------
            % 光伏24h预测
            %% ------------------------------------------------

            if freezePV ...
                    && ki>1

                basePV24 = ...
                    frozenPV48( ...
                    startSlot: ...
                    (startSlot+143));

            else

                wNow = ...
                    wDynamic(kd,ki);


                basePV24 = ...
                    makeOfficialPV24Blend( ...
                    F, ...
                    pvAll, ...
                    dateAll, ...
                    d, ...
                    hIssue, ...
                    wNow);

            end


            %% ------------------------------------------------
            % 联合残差场景
            %% ------------------------------------------------

            S = ...
                scenarioCache{kd,ki};


            loadScenario = ...
                max( ...
                baseLoad24(:) ...
                +S.loadCenter, ...
                0);


            pvScenario = ...
                max( ...
                basePV24(:) ...
                +S.pvCenter, ...
                0);


            prob = ...
                S.prob;


            %% ------------------------------------------------
            % 24h电价：
            %
            % 例如6时：
            % col37(6:10) ... col144(next 0:00)
            % col1(next 0:10) ... col36(next 6:00)
            %% ------------------------------------------------

            price24 = ...
                [ ...
                price(startSlot:end); ...
                price(1:(startSlot-1)) ...
                ];


            qCurrent = ...
                nTime-startSlot+1;


            if ki==1

                basePlanRemain = ...
                    [];

            else

                basePlanRemain = ...
                    g0(startSlot:end);

            end


            P = ...
                solveRolling24hLP( ...
                loadScenario, ...
                pvScenario, ...
                prob, ...
                price24, ...
                qCurrent, ...
                basePlanRemain, ...
                Ecurrent, ...
                forceFinalToday, ...
                Efinal, ...
                dt, ...
                eta, ...
                Emin, ...
                Emax, ...
