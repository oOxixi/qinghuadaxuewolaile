% 06:10 ... 次日06:00
%
% h=12：
% 12:10 ... 次日12:00
%
% h=18：
% 18:10 ... 次日18:00
%% ============================================================

function path = extractActual24( ...
    data, ...
    d, ...
    issueHour)


startSlot = ...
    issueHour*6+1;


if issueHour==0

    %% 当前行本身就是：
    % 00:10 ... 次日00:00

    path = ...
        data(d,:)';


elseif d<size(data,1)

    %% 今日：发布时间后10min -> 次日0点

    todayPart = ...
        data( ...
        d, ...
        startSlot:end);


    %% 次日：0:10 -> 发布时间

    nextPart = ...
        data( ...
        d+1, ...
        1:(startSlot-1));


    path = ...
        [ ...
        todayPart, ...
        nextPart ...
        ]';

else

    path = ...
        [];

end

end


%% ============================================================
% 局部函数15
% AS-Ridge负载
%% ============================================================

function [predToday,predNext] = buildCausalLoadASRidge( ...
    loadAll, ...
    dateAll, ...
    tau, ...
    lambda, ...
    maxIter, ...
    tol, ...
    windowDays)


[nDay,nTime] = ...
    size(loadAll);


predToday = ...
    nan( ...
    nDay, ...
    nTime);


predNext = ...
    nan( ...
    nDay, ...
    nTime);


slot = ...
    (0:nTime-1)';


sinDay = ...
    sin( ...
    2*pi*slot/nTime);


cosDay = ...
    cos( ...
    2*pi*slot/nTime);


for d = 16:nDay

    firstDay = ...
        max( ...
        15, ...
        d-windowDays);


    trainDays = ...
        firstDay:(d-1);


    X = ...
        zeros( ...
        length(trainDays)*nTime, ...
        7);


    y = ...
        zeros( ...
        length(trainDays)*nTime, ...
        1);


    r0 = ...
        1;


    for j = trainDays

        rr = ...
            r0:(r0+nTime-1);


        wd = ...
            weekday( ...
            dateAll(j));


        X(rr,:) = ...
            [ ...
            loadAll(j-1,:)', ...
            loadAll(j-7,:)', ...
            loadAll(j-14,:)', ...
            sinDay, ...
            cosDay, ...
            repmat( ...
            sin(2*pi*(wd-1)/7), ...
            nTime,1), ...
            repmat( ...
            cos(2*pi*(wd-1)/7), ...
            nTime,1) ...
            ];


        y(rr) = ...
            loadAll(j,:)';


        r0 = ...
            r0+nTime;

    end


    wdToday = ...
        weekday( ...
        dateAll(d));


    Xtoday = ...
        [ ...
        loadAll(d-1,:)', ...
        loadAll(d-7,:)', ...
        loadAll(d-14,:)', ...
        sinDay, ...
        cosDay, ...
        repmat( ...
        sin(2*pi*(wdToday-1)/7), ...
        nTime,1), ...
        repmat( ...
        cos(2*pi*(wdToday-1)/7), ...
        nTime,1) ...
        ];


    yToday = ...
        fitASRidgeLocal( ...
        X, ...
        y, ...
        Xtoday, ...
        tau, ...
        lambda, ...
        maxIter, ...
        tol);


    wdNext = ...
        weekday( ...
        dateAll(d) ...
        +days(1));


    Xnext = ...
        [ ...
        yToday, ...
        loadAll(d+1-7,:)', ...
        loadAll(d+1-14,:)', ...
        sinDay, ...
        cosDay, ...
        repmat( ...
        sin(2*pi*(wdNext-1)/7), ...
        nTime,1), ...
        repmat( ...
        cos(2*pi*(wdNext-1)/7), ...
        nTime,1) ...
        ];


    yNext = ...
        fitASRidgeLocal( ...
        X, ...
        y, ...
        Xnext, ...
        tau, ...
        lambda, ...
        maxIter, ...
        tol);


    predToday(d,:) = ...
        max( ...
        yToday, ...
        0)';


    predNext(d,:) = ...
        max( ...
        yNext, ...
        0)';

end

end


%% ============================================================
% 局部函数16
% AS-Ridge拟合
%% ============================================================

function yPred = fitASRidgeLocal( ...
    Xtrain, ...
    Ytrain, ...
    Xtest, ...
    tau, ...
    lambda, ...
    maxIter, ...
    tol)


muX = ...
    mean( ...
    Xtrain, ...
    1);


sdX = ...
    std( ...
    Xtrain, ...
    0, ...
    1);


sdX( ...
    sdX<1e-10 ...
    |~isfinite(sdX)) = ...
    1;


Xtr = ...
    (Xtrain-muX) ...
    ./sdX;


Xte = ...
    (Xtest-muX) ...
    ./sdX;


muY = ...
    mean(Ytrain);


sdY = ...
    std(Ytrain);


if sdY<1e-10 ...
        || ~isfinite(sdY)

    sdY = ...
        1;

end


y = ...
    (Ytrain-muY) ...
    /sdY;


X1 = ...
    [ ...
    ones(size(Xtr,1),1), ...
    Xtr ...
    ];


Xt = ...
    [ ...
    ones(size(Xte,1),1), ...
    Xte ...
    ];


R = ...
    eye( ...
    size(X1,2));


R(1,1) = ...
    0;


beta = ...
    ( ...
    X1'*X1 ...
    +lambda*R ...
    ) ...
    \(X1'*y);


for iter = 1:maxIter

    e = ...
        y ...
        -X1*beta;


    w = ...
        (1-tau) ...
        *ones(size(e));


    w(e>=0) = ...
        tau;


    w = ...
        max( ...
        w, ...
        1e-6);


    Xw = ...
        X1 ...
        .*sqrt(w);


    yw = ...
        y ...
        .*sqrt(w);


    betaNew = ...
        ( ...
        Xw'*Xw ...
        +lambda*R ...
        ) ...
        \(Xw'*yw);


    change = ...
        norm( ...
        betaNew-beta) ...
        /max( ...
        norm(beta), ...
        1e-8);


    beta = ...
        betaNew;


    if change<tol

        break;

    end

end


yPred = ...
    (Xt*beta) ...
    *sdY ...
    +muY;


yPred = ...
    yPred(:);

end


