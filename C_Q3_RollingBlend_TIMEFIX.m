%% ============================================================
% 局部函数19
% 发布时间解析
%% ============================================================

function h = parseIssueHour(x)


h = ...
    NaN;


if iscell(x)

    if isempty(x)

        return;

    end


    x = ...
        x{1};

end


if isduration(x)

    h = ...
        mod( ...
        round(hours(x)), ...
        24);


    return;

end


if isdatetime(x)

    if ~isnat(x)

        h = ...
            hour(x);

    end


    return;

end


if isnumeric(x)

    if isempty(x) ...
            || isnan(x)

        return;

    end


    if x>=0 ...
            && x<1

        h = ...
            mod( ...
            round(24*x), ...
            24);


        return;

    end


    if x>=0 ...
            && x<=24

        h = ...
            round(x);


        if h==24

            h = ...
                0;

        end


        return;

    end

end


s = ...
    strtrim( ...
    string(x));


token = ...
    regexp( ...
    char(s), ...
    '(\d{1,2})\s*:', ...
    'tokens','once');


if ~isempty(token)

    h = ...
        mod( ...
        str2double(token{1}), ...
        24);

end

end


