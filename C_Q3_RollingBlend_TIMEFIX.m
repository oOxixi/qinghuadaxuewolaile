            '第1天没有前一天数据，无法取得0时锚点。');

    end


    value = ...
        pvAll( ...
        d-1, ...
        144);


else

    issueCol = ...
        issueHour*6;


    value = ...
        pvAll( ...
        d, ...
        issueCol);

