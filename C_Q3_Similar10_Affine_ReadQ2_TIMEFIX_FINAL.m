function y = valueToDouble(x)


y = ...
    NaN;


if iscell(x)

    if isempty(x)

        return;

    end


    x = ...
        x{1};

end


if isnumeric(x)

    if ~isempty(x)

        y = ...
            double(x(1));

    end

    return;

end


if islogical(x)

    y = ...
        double(x);

    return;

end


s = ...
    strtrim(string(x));


if ismissing(s) ...
        ||strlength(s)==0

    return;

end


y = ...
    str2double(s);


end


