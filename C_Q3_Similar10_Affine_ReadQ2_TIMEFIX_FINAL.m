function A = replayActualBlockWithBase( ...
    Pload, ...
    Ppv, ...
    Wgrid, ...
    WchPlan, ...
    WdisPlan, ...
    Estart, ...
    globalSlots, ...
    forceFinalToday, ...
    Efinal, ...
    eta, ...
    Emin, ...
    Emax, ...
    Wmax)


dt = ...
    1/6;


Wload = ...
    Pload(:)*dt;


Wpv = ...
    Ppv(:)*dt;


Wgrid = ...
    Wgrid(:);


WchPlan = ...
    WchPlan(:);


WdisPlan = ...
    WdisPlan(:);


N = ...
    length(Wgrid);


Wch = ...
    zeros(N,1);


Wdis = ...
    zeros(N,1);


Wem = ...
    zeros(N,1);


Wsur = ...
    zeros(N,1);


E = ...
    zeros(N+1,1);


E(1) = ...
    Estart;


for j = 1:N

    ec = ...
        E(j);


    tGlobal = ...
        globalSlots(j);


    %% --------------------------------------------------------
    % 为强制年末SOC预留可达区间
    %% --------------------------------------------------------

    if forceFinalToday

        remainingSlots = ...
            144-tGlobal;


        nextLow = ...
            max( ...
            Emin, ...
            Efinal ...
            -remainingSlots*eta*Wmax);


        nextHigh = ...
            min( ...
            Emax, ...
            Efinal ...
            +remainingSlots*Wmax/eta);

    else

        nextLow = ...
            Emin;


        nextHigh = ...
            Emax;

    end


    %% --------------------------------------------------------
    % 基础充放电计划
    %% --------------------------------------------------------

    c = ...
        min( ...
        max(WchPlan(j),0), ...
        Wmax);


    d = ...
        min( ...
        max(WdisPlan(j),0), ...
        Wmax);


    en = ...
        ec ...
        +eta*c ...
        -d/eta;


    %% SOC过低：先减放电
    if en<nextLow

        rd = ...
            min( ...
            d, ...
            (nextLow-en)*eta);


        d = ...
            d-rd;


        en = ...
            ec ...
            +eta*c ...
            -d/eta;

    end


    %% SOC过高：先减充电
    if en>nextHigh

        rc = ...
            min( ...
            c, ...
            (en-nextHigh)/eta);


        c = ...
            c-rc;


        en = ...
            ec ...
            +eta*c ...
            -d/eta;

    end


    %% --------------------------------------------------------
    % 当前真实缺口
    %% --------------------------------------------------------

    residual = ...
        Wload(j) ...
        -Wpv(j) ...
        -Wgrid(j) ...
        -(d-c);


    %% ========================================================
    % 缺电：
    % 先减少充电
    % 再增加放电
    % 最后紧急购电
    %% ========================================================

    if residual>1e-12

        reduceCharge = ...
            min( ...
            [ ...
            residual, ...
            c, ...
            max( ...
            (en-nextLow)/eta, ...
            0) ...
            ]);


        c = ...
            c-reduceCharge;


        residual = ...
            residual-reduceCharge;


        en = ...
            en ...
            -eta*reduceCharge;


        if residual>1e-12

            extraDis = ...
                min( ...
                [ ...
                residual, ...
                Wmax-d, ...
                eta*max(en-nextLow,0) ...
                ]);


            d = ...
                d+extraDis;


            residual = ...
                residual-extraDis;


            en = ...
                en ...
                -extraDis/eta;

        end


        Wem(j) = ...
            max(residual,0);


    %% ========================================================
    % 富余：
    % 先减少放电
    % 再增加充电
    % 最后弃电
    %% ========================================================

    elseif residual<-1e-12

        surplus = ...
            -residual;


        reduceDis = ...
            min( ...
            [ ...
            surplus, ...
            d, ...
            eta*max(nextHigh-en,0) ...
            ]);


        d = ...
            d-reduceDis;


        surplus = ...
            surplus-reduceDis;


        en = ...
            en ...
            +reduceDis/eta;


        if surplus>1e-12

            extraCh = ...
                min( ...
                [ ...
                surplus, ...
                Wmax-c, ...
                max(nextHigh-en,0)/eta ...
                ]);


            c = ...
                c+extraCh;


            surplus = ...
                surplus-extraCh;


            en = ...
                en ...
                +eta*extraCh;

        end


        Wsur(j) = ...
            max(surplus,0);

    end


    Enew = ...
        ec ...
        +eta*c ...
        -d/eta;


    if Enew<nextLow-1e-6 ...
            ||Enew>nextHigh+1e-6

        error( ...
            '实际回放SOC越界：slot=%d SOC=%.9f', ...
            tGlobal, ...
            Enew);

    end


    Wch(j) = ...
        c;


    Wdis(j) = ...
        d;


    E(j+1) = ...
        Enew;

end


A.Wch = ...
    Wch;


A.Wdis = ...
    Wdis;


A.Wem = ...
    Wem;


A.Wsur = ...
    Wsur;


A.E = ...
    E;


A.Eend = ...
    E(end);


end


