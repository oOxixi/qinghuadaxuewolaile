    %% --------------------------------------------------------

    nextPart = ...
        predLoad( ...
        kd, ...
        1:startSlot-1);

else

    load24 = ...
        [];

    return;

end


load24 = ...
    [ ...
    todayPart, ...
    nextPart ...
    ]';


end


