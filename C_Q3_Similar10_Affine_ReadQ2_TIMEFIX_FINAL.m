    for c = 1:nCol

        txt = ...
            replace( ...
            strtrim( ...
            string(C{headerRow,c})), ...
            " ", ...
            "");


        if txt==sprintf('预报%d小时',h) ...
                ||txt==sprintf('预测%d小时',h)

            forecastCols(h) = ...
                c;

