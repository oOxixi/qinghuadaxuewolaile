%% ============================================================
% 局部函数7
% PV动态融合权重
%% ============================================================

function [w,nHistory] = getRollingPVBlendWeight( ...
    L, ...
    issueHour, ...
    currentTime, ...
    windowN, ...
    minHistory)


valid = ...
    L.complete ...
    &L.issueHour==issueHour ...
    &( ...
    L.issueTime+hours(24) ...
    <=currentTime);


rows = ...
    find(valid);


if isempty(rows)

    w = ...
        1;


    nHistory = ...
        0;


    return;

end


[~,ord] = ...
    sort(L.issueTime(rows));


rows = ...
    rows(ord);


firstKeep = ...
    max( ...
    1, ...
    length(rows)-windowN+1);


rows = ...
    rows(firstKeep:end);


nHistory = ...
    length(rows);


if nHistory<minHistory

    w = ...
        1;


    return;

end


formal = ...
    L.formal(rows,:);


history = ...
    L.history(rows,:);


actual = ...
    L.actual(rows,:);


formal = ...
    formal(:);


history = ...
    history(:);


actual = ...
    actual(:);


good = ...
    isfinite(formal) ...
    &isfinite(history) ...
    &isfinite(actual);


formal = ...
    formal(good);


history = ...
    history(good);


actual = ...
    actual(good);


den = ...
    sum( ...
    (formal-history).^2);


if isempty(actual) ...
        ||den<1e-12

    w = ...
        1;


    return;

end


w = ...
    sum( ...
    (actual-history) ...
    .*(formal-history)) ...
    /den;


w = ...
    min( ...
    max(w,0), ...
    1);


end


