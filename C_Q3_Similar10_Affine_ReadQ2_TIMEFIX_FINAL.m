function S = getSimilarResidualScenarios( ...
    Rlib, ...
    issueHour, ...
    currentTime, ...
    currentLoad24, ...
    currentPV24, ...
    historyWindow, ...
    minHistory, ...
    similarCount)


%% ------------------------------------------------------------
% 必须已经完整观察24h真实结果
%% ------------------------------------------------------------

valid = ...
    Rlib.complete ...
    &Rlib.issueHour==issueHour ...
    &( ...
    Rlib.issueTime+hours(24) ...
    <=currentTime);


rows = ...
    find(valid);


if isempty(rows)

    S.netResidual = ...
        zeros(1,144);


    S.prob = ...
        1;


    S.nSelected = ...
        1;


    S.nHistory = ...
        0;


    S.meanDistance = ...
        NaN;


    return;

end


%% ------------------------------------------------------------
% 最近30条
%% ------------------------------------------------------------

[~,ord] = ...
    sort(Rlib.issueTime(rows));


rows = ...
    rows(ord);


firstKeep = ...
    max( ...
    1, ...
    length(rows)-historyWindow+1);


rows = ...
    rows(firstKeep:end);


nHistory = ...
    length(rows);


if nHistory<minHistory

    S.netResidual = ...
        zeros(1,144);


    S.prob = ...
        1;


    S.nSelected = ...
        1;


    S.nHistory = ...
        nHistory;


    S.meanDistance = ...
        NaN;


    return;

end


currentLoad24 = ...
    currentLoad24(:)';


currentPV24 = ...
    currentPV24(:)';


loadScale = ...
    max( ...
    mean(abs(currentLoad24)), ...
    1);


pvScale = ...
    max( ...
    mean(abs(currentPV24)), ...
    1);


loadDistance = ...
    sqrt( ...
    mean( ...
    ( ...
    ( ...
    Rlib.baseLoad(rows,:) ...
    -currentLoad24 ...
    ) ...
    /loadScale ...
    ).^2, ...
    2));


pvDistance = ...
    sqrt( ...
    mean( ...
    ( ...
    ( ...
    Rlib.basePV(rows,:) ...
    -currentPV24 ...
    ) ...
    /pvScale ...
    ).^2, ...
    2));


totalDistance = ...
    loadDistance ...
    +pvDistance;


[~,order] = ...
    sort( ...
    totalDistance, ...
    'ascend');


keepN = ...
    min( ...
    similarCount, ...
    length(order));


keep = ...
    order(1:keepN);


selectedRows = ...
    rows(keep);


S.netResidual = ...
    Rlib.eNet(selectedRows,:);


%% 与问题2P2一致：相似日等概率
S.prob = ...
    ones(keepN,1) ...
    /keepN;


S.nSelected = ...
    keepN;


S.nHistory = ...
    nHistory;


S.meanDistance = ...
    mean( ...
    totalDistance(keep));


S.selectedDate = ...
    Rlib.date(selectedRows);


S.distance = ...
    totalDistance(keep);


end


