% 函数5：写144点矩阵
%% ============================================================

function write144Matrix( ...
    filename, ...
    sheetName, ...
    dates, ...
    M)


dateText = ...
    string( ...
    dates, ...
    'yyyy-MM-dd');


header = ...
    cell(1,145);


header{1,1} = ...
    '日期';


for t = 1:143

    totalMin = ...
        10*t;


    hh = ...
        floor(totalMin/60);


    mm = ...
        mod(totalMin,60);


    header{1,t+1} = ...
        sprintf( ...
        '%02d:%02d', ...
        hh,mm);

end


header{1,145} = ...
    '00:00+1';


writecell( ...
    header, ...
    filename, ...
    'Sheet',sheetName, ...
    'Range','A1');


writecell( ...
    cellstr(dateText), ...
    filename, ...
    'Sheet',sheetName, ...
    'Range','A2');


writematrix( ...
    M, ...
    filename, ...
    'Sheet',sheetName, ...
    'Range','B2');

end