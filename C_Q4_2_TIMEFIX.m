        sum( ...
        EmergencyCostDayAll(:,combo)));


    fprintf( ...
        '总成本：%.2f 元\n', ...
        sum( ...
        ActualPlanCostDayAll(:,combo)) ...
        +sum( ...
        EmergencyCostDayAll(:,combo)));


