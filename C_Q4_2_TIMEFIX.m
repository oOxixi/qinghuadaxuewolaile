            solveDailyPlanTerminalSOC( ...
            loadForecast, ...
            pvForecastDay, ...
            predictedPriceDay, ...
            EdayStart, ...
            terminalLow, ...
            terminalHigh, ...
            dt, ...
            eta_ch, ...
            eta_dis, ...
            Emin, ...
            Emax, ...
