    q80Correction = ...
        zeros( ...
        nPredDay, ...
        nTime);


    calibrationActive = ...
        false( ...
        nPredDay, ...
        1);


    for d = 1:nPredDay

        histEnd = ...
            d-1;


        histStart = ...
            max( ...
            1, ...
            d-ROLLING_WINDOW_DAYS);


        if histEnd<histStart

            continue;

        end


        nHist = ...
            histEnd-histStart+1;


        if nHist<MIN_HISTORY_DAYS

            continue;

        end


        calibrationActive(d) = ...
            true;


        for t = 1:nTime

            r = ...
                residualNet( ...
                histStart:histEnd, ...
                t);


            r = ...
                r(isfinite(r));


            if length(r)>=MIN_HISTORY_DAYS

                q80Correction(d,t) = ...
                    quantile( ...
                    r, ...
                    Q_LEVEL);

            end

        end

    end


    correctedNet = ...
        forecastNet ...
        +q80Correction;


    correctedLoad = ...
        max( ...
        correctedNet ...
        +pvForecast, ...
        0);


    qUse = ...
        q80Correction( ...
        repmat( ...
        calibrationActive, ...
        1,nTime));


    if isempty(qUse)

        q80MeanCombo(combo) = ...
            0;

    else

        q80MeanCombo(combo) = ...
