            plan.Wgrid';


        planChargeAll(d,:,combo) = ...
            plan.Wch';


        planDischargeAll(d,:,combo) = ...
            plan.Wdis';


        planCurtailAll(d,:,combo) = ...
            plan.Wcut';


        %% ----------------------------------------------------
        % 优化时认为的购电成本
