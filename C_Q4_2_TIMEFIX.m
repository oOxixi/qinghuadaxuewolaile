function plan = solveDailyPlanTerminalSOC( ...
    Pload, ...
    Pv, ...
    price, ...
    Estart, ...
    terminalLow, ...
    terminalHigh, ...
    dt, ...
    eta_ch, ...
    eta_dis, ...
    Emin, ...
    Emax, ...
    Wmax, ...
    cyclePenalty, ...
    curtailPenalty, ...
    options)


N = ...
    length(price);


Wload = ...
    Pload(:)*dt;


Wpv = ...
    Pv(:)*dt;


price = ...
    price(:);


idxGrid = ...
    1:N;


idxCh = ...
    N+(1:N);


idxDis = ...
    2*N+(1:N);


idxCut = ...
    3*N+(1:N);


idxE = ...
    4*N+(1:N+1);


nVar = ...
    5*N+1;


f = ...
    zeros(nVar,1);


f(idxGrid) = ...
    price;


f(idxCh) = ...
    cyclePenalty;


f(idxDis) = ...
    cyclePenalty;


f(idxCut) = ...
    curtailPenalty;


Aeq = ...
    zeros( ...
    2*N+1, ...
    nVar);


beq = ...
    zeros( ...
    2*N+1, ...
    1);


%% 供需平衡

for t = 1:N

    Aeq(t,idxGrid(t)) = ...
        1;


    Aeq(t,idxCh(t)) = ...
        -1;


    Aeq(t,idxDis(t)) = ...
        1;


    Aeq(t,idxCut(t)) = ...
        -1;


    beq(t) = ...
        Wload(t) ...
        -Wpv(t);

end


%% SOC

for t = 1:N

    r = ...
        N+t;


    Aeq(r,idxE(t)) = ...
        -1;


    Aeq(r,idxE(t+1)) = ...
        1;


    Aeq(r,idxCh(t)) = ...
        -eta_ch;


    Aeq(r,idxDis(t)) = ...
        1/eta_dis;

end


Aeq(2*N+1,idxE(1)) = ...
    1;


beq(2*N+1) = ...
    Estart;


lb = ...
    zeros(nVar,1);


ub = ...
    inf(nVar,1);


ub(idxCh) = ...
    Wmax;


ub(idxDis) = ...
    Wmax;


ub(idxCut) = ...
    Wpv;


lb(idxE) = ...
    Emin;


ub(idxE) = ...
    Emax;


lb(idxE(end)) = ...
    terminalLow;


ub(idxE(end)) = ...
    terminalHigh;


[x,~,exitflag,output] = ...
    linprog( ...
    f, ...
    [],[], ...
    Aeq,beq, ...
    lb,ub, ...
    options);


if exitflag<=0

    error( ...
        '计划LP失败：%s', ...
        output.message);

end


plan.Wgrid = ...
    x(idxGrid);


plan.Wch = ...
    x(idxCh);


plan.Wdis = ...
    x(idxDis);


plan.Wcut = ...
    x(idxCut);


plan.E = ...
    x(idxE);

end


%% ============================================================
% 函数2：实际严格因果回放
%% ============================================================

function replay = replayActualDayCausalAllowSimultaneous( ...
    Pload, ...
    Pv, ...
    Wgrid, ...
    WchPlan, ...
    WdisPlan, ...
    Estart, ...
    dt, ...
    eta_ch, ...
    eta_dis, ...
    Emin, ...
    Emax, ...
    Wmax, ...
    forceFinalSOC, ...
    EfinalTarget)


N = ...
    length(Wgrid);


Wload = ...
    Pload(:)*dt;


Wpv = ...
    Pv(:)*dt;


Wgrid = ...
    Wgrid(:);


WchPlan = ...
    WchPlan(:);


WdisPlan = ...
    WdisPlan(:);


Wch = ...
    zeros(N,1);


Wdis = ...
    zeros(N,1);


Wspill = ...
    zeros(N,1);


Wem = ...
    zeros(N,1);


E = ...
    zeros(N+1,1);


E(1) = ...
    Estart;


for t = 1:N

    Ecurrent = ...
        E(t);


    EnextLow = ...
        Emin;


    EnextHigh = ...
        Emax;


    if forceFinalSOC

        remainingSlots = ...
            N-t;


        reachLow = ...
            EfinalTarget ...
            -remainingSlots ...
            *eta_ch ...
            *Wmax;


        reachHigh = ...
            EfinalTarget ...
            +remainingSlots ...
            *Wmax/eta_dis;


        EnextLow = ...
            max( ...
            Emin, ...
            reachLow);


        EnextHigh = ...
            min( ...
            Emax, ...
            reachHigh);

    end


    WchNow = ...
        min( ...
        max(WchPlan(t),0), ...
        Wmax);


    WdisNow = ...
        min( ...
        max(WdisPlan(t),0), ...
        Wmax);


    Enew = ...
        Ecurrent ...
        +eta_ch*WchNow ...
        -WdisNow/eta_dis;


    if Enew<EnextLow

        need = ...
            EnextLow-Enew;


        reduceDis = ...
            min( ...
            WdisNow, ...
            need*eta_dis);


        WdisNow = ...
            WdisNow ...
            -reduceDis;


        Enew = ...
            Ecurrent ...
            +eta_ch*WchNow ...
            -WdisNow/eta_dis;


        if Enew<EnextLow-1e-10

            addCh = ...
                min( ...
                Wmax-WchNow, ...
                (EnextLow-Enew)/eta_ch);


            WchNow = ...
                WchNow ...
                +addCh;


            Enew = ...
                Ecurrent ...
                +eta_ch*WchNow ...
                -WdisNow/eta_dis;

        end

    end


    if Enew>EnextHigh

        need = ...
            Enew-EnextHigh;


        reduceCh = ...
            min( ...
            WchNow, ...
            need/eta_ch);


        WchNow = ...
            WchNow ...
            -reduceCh;


        Enew = ...
            Ecurrent ...
            +eta_ch*WchNow ...
            -WdisNow/eta_dis;


        if Enew>EnextHigh+1e-10

            addDis = ...
                min( ...
                Wmax-WdisNow, ...
                (Enew-EnextHigh)*eta_dis);


            WdisNow = ...
                WdisNow ...
                +addDis;


            Enew = ...
                Ecurrent ...
                +eta_ch*WchNow ...
                -WdisNow/eta_dis;

        end

    end


    residual = ...
        Wload(t) ...
        +WchNow ...
        -Wpv(t) ...
        -Wgrid(t) ...
        -WdisNow;


    if residual>1e-12

        maxReduceChSOC = ...
            max( ...
            (Enew-EnextLow)/eta_ch, ...
            0);


        reduceCh = ...
            min( ...
            [ ...
            residual, ...
            WchNow, ...
            maxReduceChSOC ...
            ]);


        WchNow = ...
            WchNow ...
            -reduceCh;


        residual = ...
            residual ...
            -reduceCh;


        Enew = ...
            Enew ...
            -eta_ch*reduceCh;


        if residual>1e-12

            maxExtraDisSOC = ...
                eta_dis ...
                *max( ...
                Enew-EnextLow, ...
                0);


            extraDis = ...
                min( ...
                [ ...
                residual, ...
                Wmax-WdisNow, ...
                maxExtraDisSOC ...
                ]);


            WdisNow = ...
                WdisNow ...
                +extraDis;


            residual = ...
                residual ...
                -extraDis;


            Enew = ...
                Enew ...
                -extraDis/eta_dis;

        end


        Wem(t) = ...
            max(residual,0);


    elseif residual<-1e-12

        surplus = ...
            -residual;


        maxReduceDisSOC = ...
            eta_dis ...
            *max( ...
            EnextHigh-Enew, ...
            0);


        reduceDis = ...
            min( ...
            [ ...
            surplus, ...
            WdisNow, ...
            maxReduceDisSOC ...
            ]);


        WdisNow = ...
            WdisNow ...
            -reduceDis;


        surplus = ...
            surplus ...
            -reduceDis;


        Enew = ...
            Enew ...
            +reduceDis/eta_dis;


        if surplus>1e-12

            maxExtraChSOC = ...
                max( ...
                EnextHigh-Enew, ...
                0) ...
                /eta_ch;


            extraCh = ...
                min( ...
                [ ...
                surplus, ...
                Wmax-WchNow, ...
                maxExtraChSOC ...
                ]);


            WchNow = ...
                WchNow ...
                +extraCh;


            surplus = ...
                surplus ...
                -extraCh;


            Enew = ...
                Enew ...
                +eta_ch*extraCh;

        end


        Wspill(t) = ...
            max(surplus,0);

    end


    Wch(t) = ...
        WchNow;


    Wdis(t) = ...
        WdisNow;


    E(t+1) = ...
        Ecurrent ...
        +eta_ch*Wch(t) ...
        -Wdis(t)/eta_dis;


    if E(t+1)<Emin-1e-6 ...
            || E(t+1)>Emax+1e-6

        error( ...
            'SOC越界：t=%d,E=%.6f', ...
            t,E(t+1));

    end


    balanceError = ...
        Wgrid(t) ...
        +Wpv(t) ...
        +Wdis(t) ...
        +Wem(t) ...
        -Wload(t) ...
        -Wch(t) ...
        -Wspill(t);


    if abs(balanceError)>1e-5

        error( ...
            '实际供需平衡失败：t=%d,error=%.8f', ...
            t,balanceError);

    end

end


replay.Wch = ...
    Wch;


replay.Wdis = ...
    Wdis;


replay.Wspill = ...
    Wspill;


replay.Wem = ...
    Wem;


replay.E = ...
    E;


replay.Eend = ...
    E(end);

end


