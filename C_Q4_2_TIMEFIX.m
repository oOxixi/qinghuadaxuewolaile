priceForecastRun = ...
    nan( ...
    nPredDay, ...
    nTime);


for kd = 1:nPredDay

    d = ...
        targetDays(kd);


    targetWD = ...
        weekday( ...
        datesAll(d));


    histDays = ...
        1:(d-1);


    histWD = ...
        arrayfun( ...
        @(x) ...
        weekday(datesAll(x)), ...
        histDays);


    sameDays = ...
        histDays( ...
        histWD==targetWD);


    if length(sameDays)<max(PRICE_KL,PRICE_KS)

        error( ...
            '%s以前同星期日历史不足。', ...
            string(datesAll(d)));

    end


    %% --------------------------------------------------------
    % 日均价
    %% --------------------------------------------------------

    meanDays = ...
        sameDays( ...
        end-PRICE_KL+1:end);


    predDailyMean = ...
        mean( ...
        mean( ...
        priceAll(meanDays,:), ...
        2));


    %% --------------------------------------------------------
    % 日内相对形状
    %% --------------------------------------------------------

    shapeDays = ...
        sameDays( ...
        end-PRICE_KS+1:end);


    shapeMatrix = ...
        zeros( ...
        PRICE_KS, ...
        nTime);


    for k = 1:PRICE_KS

        onePrice = ...
            priceAll( ...
            shapeDays(k), ...
            :);


        oneMean = ...
            mean(onePrice);


        shapeMatrix(k,:) = ...
            onePrice ...
            /oneMean;

    end


    predShape = ...
        mean( ...
        shapeMatrix, ...
        1);


    %% --------------------------------------------------------
    % 最终144点预测
    %% --------------------------------------------------------

    priceForecastRun(kd,:) = ...
        max( ...
        predDailyMean ...
        .*predShape, ...
        0);

end


