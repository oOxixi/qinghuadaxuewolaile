%% ============================================================
% 局部函数25
% 分钟转时间文字
%% ============================================================

function txt = formatResultTimeQ43(totalMinute)


dayAdd = ...
    floor(totalMinute/1440);


minuteOfDay = ...
    mod(totalMinute,1440);


hh = ...
    floor(minuteOfDay/60);


mm = ...
    mod(minuteOfDay,60);


if dayAdd==0

    txt = ...
        sprintf( ...
        '%d:%02d', ...
        hh, ...
        mm);

else

    txt = ...
        sprintf( ...
        '%d:%02d+1', ...
        hh, ...
        mm);

end

