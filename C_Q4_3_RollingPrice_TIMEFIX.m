%% ============================================================
% 局部函数1
% Q4-3运行一个策略
%% ============================================================

function R = runOneStrategyQ43( ...
    strategyName, ...
    updateMask, ...
    freezePV, ...
    targetDays, ...
    predDates, ...
    dateAll, ...
    loadAll, ...
    pvAll, ...
    loadForecastToday, ...
    loadForecastNext, ...
    F, ...
    scenarioCache, ...
    wDynamic, ...
    priceAll, ...
    priceForecastCache, ...
    useTerminalValue, ...
    dt, ...
    eta, ...
    Emin, ...
    Emax, ...
    Einitial, ...
    Efinal, ...
    Wmax, ...
    cyclePenalty, ...
    curtailPenalty, ...
    forceFinalSOC6000, ...
    lpOptions)


nDay = ...
    length(targetDays);


nTime = ...
    144;


issueHours = ...
    [0,6,12,18];


plan0 = ...
    zeros(nDay,nTime);


executedPlan = ...
    zeros(nDay,nTime);


planAfter = ...
    nan(nDay,nTime,4);


actualCharge = ...
    zeros(nDay,nTime);


actualDischarge = ...
    zeros(nDay,nTime);


actualEmergency = ...
    zeros(nDay,nTime);


actualSurplus = ...
    zeros(nDay,nTime);


SOCstart = ...
    zeros(nDay,1);


SOCend = ...
    zeros(nDay,1);


retainedPlanCostDay = ...
    zeros(nDay,1);


increaseCostDay = ...
    zeros(nDay,1);


decreasePenaltyDay = ...
    zeros(nDay,1);


emergencyCostDay = ...
    zeros(nDay,1);


increaseEnergyDay = ...
    zeros(nDay,1);


decreaseEnergyDay = ...
    zeros(nDay,1);


adjustmentTable = ...
    table();


maxLPViolation = ...
    0;


Ecurrent = ...
    Einitial;


for kd = 1:nDay

    d = ...
        targetDays(kd);


    thisDate = ...
        dateAll(d);


    actualPriceDay = ...
        priceAll(d,:)';


    isLastDay = ...
        d==365;


    forceFinalToday = ...
        isLastDay ...
        &&forceFinalSOC6000;


    SOCstart(kd) = ...
        Ecurrent;


    if mod(kd-1,20)==0 ...
            ||isLastDay

        fprintf( ...
            '  [%03d/%03d] %s，SOC %.2f\n', ...
            kd, ...
            nDay, ...
            string(thisDate), ...
            Ecurrent);

    end


    %% --------------------------------------------------------
    % 冻结0时光伏对照
    %% --------------------------------------------------------

    w0 = ...
        wDynamic(kd,1);


    frozenPV48 = ...
        buildFrozenPV48( ...
        F, ...
        pvAll, ...
        dateAll, ...
        d, ...
        w0);


    currentPlan = ...
        zeros(nTime,1);


    g0 = ...
        zeros(nTime,1);


    for ki = 1:4

        hIssue = ...
            issueHours(ki);


        startSlot = ...
            hIssue*6+1;


        endSlot = ...
            min( ...
            startSlot+35, ...
            nTime);


        shouldOptimize = ...
            ki==1 ...
            ||updateMask(ki);


        if shouldOptimize

            %% ------------------------------------------------
            % 负载未来24h
            %% ------------------------------------------------

            baseLoad24 = ...
                makeLoadForecast24( ...
                loadForecastToday, ...
                loadForecastNext, ...
                d, ...
                hIssue);


            %% ------------------------------------------------
            % 光伏未来24h
            %% ------------------------------------------------

            if freezePV ...
                    &&ki>1

                basePV24 = ...
                    frozenPV48( ...
                    startSlot: ...
                    startSlot+143);

            else

                wNow = ...
                    wDynamic(kd,ki);


                basePV24 = ...
                    makeOfficialPV24Blend( ...
                    F, ...
                    pvAll, ...
                    dateAll, ...
                    d, ...
                    hIssue, ...
                    wNow);

            end


            %% ------------------------------------------------
            % 联合残差3情景
            %% ------------------------------------------------

            S = ...
                scenarioCache{kd,ki};


            loadScenario = ...
                max( ...
                baseLoad24(:) ...
                +S.loadCenter, ...
                0);


            pvScenario = ...
                max( ...
                basePV24(:) ...
                +S.pvCenter, ...
                0);


            prob = ...
                S.prob;


            %% ------------------------------------------------
            % ★Q4未来24h预测电价
            %% ------------------------------------------------

            price24 = ...
                priceForecastCache{kd,ki};


            price24 = ...
                price24(:);


            if length(price24)~=144

                error( ...
                    '滚动电价预测长度不是144。');

            end


            qCurrent = ...
                nTime-startSlot+1;


            if ki==1

                basePlanRemain = ...
                    [];

            else

                basePlanRemain = ...
                    g0(startSlot:end);

            end


            %% ------------------------------------------------
            % 终端储能价值
            %% ------------------------------------------------

            if useTerminalValue ...
                    &&~isLastDay

                terminalValueNow = ...
                    eta ...
                    *mean(price24);

            else

                terminalValueNow = ...
                    0;

            end


            %% ------------------------------------------------
            % 24h随机LP
            %% ------------------------------------------------

            P = ...
                solveRolling24hLP( ...
                loadScenario, ...
                pvScenario, ...
                prob, ...
                price24, ...
                qCurrent, ...
                basePlanRemain, ...
                Ecurrent, ...
                forceFinalToday, ...
                Efinal, ...
                dt, ...
                eta, ...
                Emin, ...
                Emax, ...
                Wmax, ...
                terminalValueNow, ...
                cyclePenalty, ...
                curtailPenalty, ...
                lpOptions);


            maxLPViolation = ...
                max( ...
                maxLPViolation, ...
                P.maxConstraintViolation);


            if ki==1

                g0 = ...
                    P.currentGrid;


                currentPlan = ...
                    g0;


                plan0(kd,:) = ...
                    g0';

            else

                oldPlan = ...
                    currentPlan(startSlot:end);


                currentPlan(startSlot:end) = ...
                    P.currentGrid;


                oneInc = ...
                    sum( ...
                    max( ...
                    P.currentGrid ...
                    -g0(startSlot:end), ...
                    0));


                oneDec = ...
                    sum( ...
                    max( ...
                    g0(startSlot:end) ...
                    -P.currentGrid, ...
                    0));


                logRow = ...
                    table( ...
                    string(strategyName), ...
                    thisDate, ...
                    hIssue, ...
                    wDynamic(kd,ki), ...
                    mean(price24), ...
                    sum( ...
                    abs( ...
                    P.currentGrid ...
                    -oldPlan)>1e-6), ...
                    oneInc, ...
                    oneDec, ...
                    P.objective, ...
                    P.maxConstraintViolation, ...
                    'VariableNames',{ ...
                    'Strategy', ...
                    'Date', ...
                    'IssueHour', ...
                    'PVBlendWeight', ...
                    'ForecastPriceMean', ...
                    'ChangedSlots', ...
                    'IncreaseVs0_kWh', ...
                    'DecreaseVs0_kWh', ...
                    'RollingObjective', ...
                    'MaxConstraintViolation'} ...
                    );


                adjustmentTable = ...
                    [adjustmentTable;logRow];

            end

        end


        planAfter(kd,:,ki) = ...
            currentPlan';


        %% ----------------------------------------------------
        % 仅执行下一6小时
        %% ----------------------------------------------------

        blockSlots = ...
            startSlot:endSlot;


        A = ...
            replayActualBlock( ...
            loadAll(d,blockSlots)', ...
            pvAll(d,blockSlots)', ...
            currentPlan(blockSlots), ...
            Ecurrent, ...
            blockSlots, ...
            forceFinalToday, ...
            Efinal, ...
            dt, ...
            eta, ...
            Emin, ...
            Emax, ...
            Wmax);


        executedPlan(kd,blockSlots) = ...
            currentPlan(blockSlots)';


        actualCharge(kd,blockSlots) = ...
            A.Wch';


        actualDischarge(kd,blockSlots) = ...
            A.Wdis';


        actualEmergency(kd,blockSlots) = ...
            A.Wem';


        actualSurplus(kd,blockSlots) = ...
            A.Wsur';


        Ecurrent = ...
            A.Eend;

    end


    SOCend(kd) = ...
        Ecurrent;


    %% ========================================================
    % 实际实时电价结算
    %% ========================================================

    inc = ...
        max( ...
        executedPlan(kd,:)' ...
        -g0, ...
        0);


    dec = ...
        max( ...
        g0 ...
        -executedPlan(kd,:)', ...
        0);


    retainedPlanCostDay(kd) = ...
        sum( ...
        actualPriceDay ...
        .*min( ...
        g0, ...
        executedPlan(kd,:)'));


    increaseCostDay(kd) = ...
        1.5 ...
        *sum( ...
        actualPriceDay ...
        .*inc);


    decreasePenaltyDay(kd) = ...
        0.5 ...
        *sum( ...
        actualPriceDay ...
        .*dec);


    emergencyCostDay(kd) = ...
        5 ...
        *sum( ...
        actualPriceDay ...
        .*actualEmergency(kd,:)');


    increaseEnergyDay(kd) = ...
        sum(inc);


    decreaseEnergyDay(kd) = ...
        sum(dec);

end


if forceFinalSOC6000 ...
        &&abs(SOCend(end)-Efinal)>1e-5

    error( ...
        '%s最终SOC未回到6000。', ...
        strategyName);

end


if any(SOCend<Emin-1e-5) ...
        ||any(SOCend>Emax+1e-5)

    error( ...
        '%s存在SOC越界。', ...
        strategyName);

end


dailyCost = ...
    retainedPlanCostDay ...
    +increaseCostDay ...
    +decreasePenaltyDay ...
    +emergencyCostDay;


dailyTable = ...
    table( ...
    predDates, ...
    SOCstart, ...
    SOCend, ...
    retainedPlanCostDay, ...
    increaseCostDay, ...
    decreasePenaltyDay, ...
    emergencyCostDay, ...
    dailyCost, ...
    increaseEnergyDay, ...
    decreaseEnergyDay, ...
    sum(actualEmergency,2), ...
    'VariableNames',{ ...
    'Date', ...
    'SOCstart_kWh', ...
    'SOCend_kWh', ...
    'RetainedPlanCost_Yuan', ...
    'IncreaseCost_Yuan', ...
    'DecreasePenalty_Yuan', ...
    'EmergencyCost_Yuan', ...
    'TotalCost_Yuan', ...
    'IncreaseEnergy_kWh', ...
    'DecreaseEnergy_kWh', ...
    'EmergencyEnergy_kWh'} ...
    );


R.name = ...
    strategyName;


R.plan0 = ...
    plan0;


R.executedPlan = ...
    executedPlan;


R.planAfter = ...
    planAfter;


R.actualCharge = ...
    actualCharge;


R.actualDischarge = ...
    actualDischarge;


R.actualEmergency = ...
    actualEmergency;


R.actualSurplus = ...
    actualSurplus;


R.SOCstart = ...
    SOCstart;


R.SOCend = ...
    SOCend;


R.dailyCost = ...
    dailyCost;


R.dailyTable = ...
    dailyTable;


R.adjustmentTable = ...
    adjustmentTable;


R.totalRetainedPlanCost = ...
    sum(retainedPlanCostDay);


R.totalIncreaseCost = ...
    sum(increaseCostDay);


R.totalDecreasePenalty = ...
    sum(decreasePenaltyDay);


R.totalEmergencyCost = ...
    sum(emergencyCostDay);


R.totalCost = ...
    sum(dailyCost);


R.totalIncreaseEnergy = ...
    sum(increaseEnergyDay);


