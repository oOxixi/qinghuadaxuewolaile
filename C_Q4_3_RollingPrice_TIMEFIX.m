%% ============================================================
% 局部函数7
% 联合残差K-means情景
%% ============================================================

function S = getJointScenarioCenters( ...
    Rlib, ...
    issueHour, ...
    currentTime, ...
    poolDays, ...
    Kscenario, ...
    seed)


valid = ...
    Rlib.complete ...
    &Rlib.issueHour==issueHour ...
    &( ...
    Rlib.issueTime+hours(24) ...
    <=currentTime);


rows = ...
    find(valid);


if isempty(rows)

    S.loadCenter = ...
        zeros(144,1);


    S.pvCenter = ...
        zeros(144,1);


    S.prob = ...
        1;


    S.nHistory = ...
        0;


    return;

end


[~,ord] = ...
    sort( ...
    Rlib.issueTime(rows));


rows = ...
    rows(ord);


firstKeep = ...
    max( ...
    1, ...
    length(rows)-poolDays+1);


rows = ...
    rows(firstKeep:end);


EL = ...
    Rlib.eLoad(rows,:);


EP = ...
    Rlib.ePV(rows,:);


nHistory = ...
    size(EL,1);


K = ...
    min( ...
    Kscenario, ...
    nHistory);


if K==1

    centerL = ...
        mean( ...
        EL, ...
        1);


    centerP = ...
        mean( ...
        EP, ...
        1);


    prob = ...
        1;

else

    scaleL = ...
        max( ...
        std( ...
        EL, ...
        0, ...
        'all'), ...
        1);


    scaleP = ...
        max( ...
        std( ...
        EP, ...
        0, ...
        'all'), ...
        1);


    Z = ...
        [ ...
        EL/scaleL, ...
        EP/scaleP ...
        ];


    rng( ...
        seed, ...
        'twister');


    clusterID = ...
        kmeans( ...
        Z, ...
        K, ...
        'Distance','sqeuclidean', ...
        'Replicates',10, ...
        'MaxIter',300, ...
        'EmptyAction','singleton');


    centerL = ...
        zeros(K,144);


    centerP = ...
        zeros(K,144);


    prob = ...
        zeros(K,1);


    for k = 1:K

        hit = ...
            clusterID==k;


        centerL(k,:) = ...
            mean( ...
            EL(hit,:), ...
            1);


        centerP(k,:) = ...
            mean( ...
            EP(hit,:), ...
            1);


        prob(k) = ...
            mean(hit);

    end


    netResidualMean = ...
        mean( ...
        centerL-centerP, ...
        2);


    [~,sortID] = ...
        sort(netResidualMean);


    centerL = ...
        centerL(sortID,:);


    centerP = ...
        centerP(sortID,:);


    prob = ...
        prob(sortID);

end


S.loadCenter = ...
    centerL';


S.pvCenter = ...
    centerP';


S.prob = ...
    prob(:)/sum(prob);


S.nHistory = ...
    nHistory;

end


