    sum(decreaseEnergyDay);


R.totalEmergencyEnergy = ...
    sum( ...
    actualEmergency, ...
    'all');


R.emergencyDays = ...
    sum( ...
    any( ...
    actualEmergency>1e-8, ...
    2));


