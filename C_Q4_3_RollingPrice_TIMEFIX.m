%% ============================================================
% 局部函数22
% 某发布时间预测未来24h实时电价
%% ============================================================

function price24 = makeRollingPrice24( ...
    priceAll, ...
    dateAll, ...
    d, ...
    issueHour, ...
    kL, ...
    kS, ...
    useRollingUpdate)


%% ------------------------------------------------------------
% 当天0时基础预测
%% ------------------------------------------------------------

[ ...
    todayBase, ...
    todayShape, ...
    ~ ...
    ] = ...
    makeBaseCalendarPriceForecast( ...
    priceAll, ...
    dateAll, ...
    dateAll(d), ...
    d-1, ...
    kL, ...
    kS);


todayForecast = ...
    todayBase;


%% ------------------------------------------------------------
% 6/12/18时：
%
% 使用已经发生的真实价格重新估计
% “当天价格水平”
%% ------------------------------------------------------------

if useRollingUpdate ...
        &&issueHour>0

    obsN = ...
        issueHour*6;


    observedPrice = ...
        priceAll( ...
        d, ...
        1:obsN)';


    observedShape = ...
        todayShape( ...
        1:obsN)';


    denom = ...
        sum( ...
        observedShape.^2);


    if denom>1e-12

        updatedLevel = ...
            sum( ...
            observedShape ...
            .*observedPrice) ...
            /denom;


        if isfinite(updatedLevel) ...
                &&updatedLevel>=0

            todayForecast = ...
                updatedLevel ...
                .*todayShape;

        end

    end

end


todayForecast = ...
    max( ...
    todayForecast, ...
    0);


%% ------------------------------------------------------------
% 次日价格：
%
% 当前日未完整结束，
% 因此只能使用截至前一天的完整历史数据
%% ------------------------------------------------------------

nextDate = ...
    dateAll(d) ...
    +days(1);


[nextForecast,~,~] = ...
    makeBaseCalendarPriceForecast( ...
    priceAll, ...
    dateAll, ...
    nextDate, ...
    d-1, ...
    kL, ...
    kS);


%% ------------------------------------------------------------
% 拼成发布时间后的连续24小时
%% ------------------------------------------------------------

startSlot = ...
    issueHour*6+1;


price24 = ...
    [ ...
    todayForecast( ...
    startSlot:end), ...
    nextForecast( ...
    1:startSlot-1) ...
    ]';


if length(price24)~=144

    error( ...
        '滚动实时电价预测不是144点。');

end

end


%% ============================================================
% 局部函数23
% 基础电价预测：
%
% 日均价 × 日内相对形状
%% ============================================================

function [ ...
    forecastDay, ...
    shapeDay, ...
    levelDay ...
    ] = ...
    makeBaseCalendarPriceForecast( ...
    priceAll, ...
    dateAll, ...
    targetDate, ...
    lastCompleteDay, ...
    kL, ...
    kS)


histDays = ...
    (1:lastCompleteDay)';


targetWeekday = ...
    weekday(targetDate);


histWeekday = ...
    weekday( ...
    dateAll(histDays));


sameWeekDays = ...
    histDays( ...
    histWeekday==targetWeekday);


if length(sameWeekDays)<max(kL,kS)

    error( ...
        '实时电价同星期历史数据不足。');

end


%% 日均价水平

meanDays = ...
    sameWeekDays( ...
    end-kL+1:end);


historicalDailyMean = ...
    mean( ...
    priceAll(meanDays,:), ...
    2);


levelDay = ...
    mean(historicalDailyMean);


%% 日内相对形状

shapeDays = ...
    sameWeekDays( ...
    end-kS+1:end);


shapeMatrix = ...
    zeros(kS,144);


for k = 1:kS

    onePrice = ...
        priceAll( ...
        shapeDays(k), ...
        :);


    oneMean = ...
        mean(onePrice);


    if abs(oneMean)<1e-12

        error( ...
            '历史日均电价接近0。');

    end


    shapeMatrix(k,:) = ...
        onePrice ...
        /oneMean;

end


shapeDay = ...
    mean( ...
    shapeMatrix, ...
    1);


forecastDay = ...
    levelDay ...
    .*shapeDay;


forecastDay = ...
    max( ...
    forecastDay, ...
    0);

end


